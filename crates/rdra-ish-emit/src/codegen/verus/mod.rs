//! `codegen --lang rust --verus`: Verus specifications beside the Rust code, so that a
//! modified core is checked against the verified model for any number of rows
//! (docs/design/verus.md). Experimental.
//!
//! The model spec (state, steps, rules) is read from the `TransitionSystem`, the one semantics
//! `check`, `verify` and the printers share; the exec types and functions from the
//! `DomainModel` the Rust printer prints. The ordinary output does not change.
//!
//! Files of the generated crate:
//!
//! | file | edited by | holds |
//! |---|---|---|
//! | `main.rs` | rdra-ish | the module list and the differential harness's entry |
//! | `types.rs` | rdra-ish | the data types |
//! | `prelude.rs` | rdra-ish | the lemmas no model changes: rows as a map, counting |
//! | `model.rs` | rdra-ish | the state, one step per action, the rules, the inductive set, preservation |
//! | `contract.rs` | rdra-ish | what each function must do on its rows, as a trait |
//! | `core.rs` | the user | the functions, as the trait's methods |
//! | `port.rs` | rdra-ish | the store boundary (trusted) and one verified port call per action |
//! | `harness.rs` | rdra-ish | the differential test against BFS successors (not verified) |

