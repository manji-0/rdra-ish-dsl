/// The Verus release the output was checked with. Another release may reject it.
pub const VERUS_RELEASE: &str = "0.2026.11.22.1ce6a59";
/// The Rust toolchain that Verus release runs on.
pub const VERUS_TOOLCHAIN: &str = "1.100.0";

/// The generated files, `(name, text)`, in the order the crate lists them.
pub type Files = Vec<(String, String)>;

/// The Verus crate for `model`, whose ordinary Rust output is `domain`; or every reason the
/// model is outside what this version covers.
pub fn generate(model: &SemanticModel, domain: &DomainModel) -> Result<Files, Vec<String>> {
    let built = TransitionSystem::build(model, Bounds::STATES, &Scope::ALL);
    let ctx = Ctx::new(model, &built.ts, domain)?;
    let atoms = model::Atoms::default();
    let model_rs = model::print(&ctx, &atoms)?;
    let exec = exec::print(&ctx, &atoms)?;
    let mut files: Files = vec![
        ("main.rs".to_string(), main_rs()),
        ("types.rs".to_string(), exec.types),
        ("prelude.rs".to_string(), prelude::print(&ctx)),
        ("model.rs".to_string(), model_rs),
        ("contract.rs".to_string(), exec.contract),
        ("core.rs".to_string(), exec.core),
        ("port.rs".to_string(), exec.port),
        ("harness.rs".to_string(), harness::print(&ctx)),
    ];
    for (name, text) in &mut files {
        *text = format!("{}{text}", header(name));
    }
    Ok(files)
}

fn header(file: &str) -> String {
    let who = if file == "core.rs" {
        "Yours to edit: Verus checks it against contract.rs."
    } else {
        "Generated; do not edit: the proofs rest on it."
    };
    format!(
        "// Generated by rdra-ish {} codegen --lang rust --verus (experimental).\n\
         // Checked with Verus {VERUS_RELEASE} on Rust {VERUS_TOOLCHAIN}. {who}\n\n",
        env!("CARGO_PKG_VERSION")
    )
}

fn main_rs() -> String {
    "#![allow(unused_imports, unused_parens, unused_variables, dead_code, non_snake_case)]\n\
     #![allow(clippy::all)]\n\
     //! The Verus crate: `verus main.rs` checks it; `verus main.rs --compile` builds the\n\
     //! differential harness (`harness.rs`).\n\n\
     pub mod types;\npub mod prelude;\npub mod model;\npub mod contract;\npub mod core;\npub mod port;\npub mod harness;\n\n\
     fn main() {\n    harness::main();\n}\n"
        .to_string()
}

