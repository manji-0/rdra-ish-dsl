/// An entity of the transition system, with the names the printers use.
pub(super) struct Ent {
    pub eid: EntId,
    /// The model id: `Loan`.
    pub id: String,
    /// snake_case: the field of `MState` and the stem of its spec functions.
    pub snake: String,
    /// The ghost row type: `LoanM`.
    pub m: String,
    /// The exec id type: `LoanId`.
    pub id_ty: String,
    /// The exec row type: `LoanRow`, or the record type of an entity with no states.
    pub row: String,
    /// The state type (`Loan`) and its variants, for an entity with states.
    pub sum: Option<Sum>,
    /// The tracked columns and keys: the fields of the ghost row.
    pub fields: Vec<MField>,
}

pub(super) struct Sum {
    pub name: String,
    /// The tag column's field in the row type.
    pub tag_field: String,
    /// `(variant struct name, enum ident)`, in the tag's value order.
    pub variants: Vec<(String, String)>,
    /// The tag's wire spellings, as `ExpectedSource::In` names them.
    pub wires: Vec<String>,
}

#[derive(Clone)]
pub(super) struct MField {
    pub var: VarId,
    /// The field name in the row and state types, and in the ghost row.
    pub name: String,
    pub ty: MTy,
    /// The state tag of a sum: not a field of the variant structs.
    pub tag: bool,
}

#[derive(Clone, PartialEq, Eq)]
pub(super) enum MTy {
    /// An enum column: its exec type and its values' identifiers, by value index.
    Enum {
        ty: String,
        idents: Vec<String>,
    },
    Bool,
    /// A key naming a row of `parent`, as the parent's id (`int` in spec).
    Key {
        parent: EntId,
    },
}

impl MTy {
    pub fn spec(&self) -> String {
        match self {
            MTy::Enum { ty, .. } => ty.clone(),
            MTy::Bool => "bool".to_string(),
            MTy::Key { .. } => "int".to_string(),
        }
    }
}

pub(super) struct Ctx<'a> {
    pub model: &'a SemanticModel,
    pub ts: &'a TransitionSystem,
    pub domain: &'a DomainModel,
    pub ents: Vec<Ent>,
}

impl<'a> Ctx<'a> {
    fn new(
        model: &'a SemanticModel,
        ts: &'a TransitionSystem,
        domain: &'a DomainModel,
    ) -> Result<Self, Vec<String>> {
        let mut why = Vec::new();
        scope(ts, domain, &mut why);
        let mut ents = Vec::new();
        for eid in ts.entity_ids() {
            match ent(ts, domain, eid) {
                Ok(e) => ents.push(e),
                Err(mut w) => why.append(&mut w),
            }
        }
        if !why.is_empty() {
            why.sort();
            why.dedup();
            return Err(why);
        }
        Ok(Ctx {
            model,
            ts,
            domain,
            ents,
        })
    }

    pub fn ent(&self, eid: EntId) -> &Ent {
        self.ents
            .iter()
            .find(|e| e.eid == eid)
            .expect("every entity")
    }

    pub fn ent_by_id(&self, id: &str) -> Option<&Ent> {
        self.ents.iter().find(|e| e.id == id)
    }

    /// The field of a tracked var.
    pub fn field(&self, var: VarId) -> (&Ent, &MField) {
        for e in &self.ents {
            if let Some(f) = e.fields.iter().find(|f| f.var == var) {
                return (e, f);
            }
        }
        unreachable!("every var the spec reads is a field: the scope check refuses others")
    }

    /// A value of `var` as a spec literal.
    pub fn lit(&self, var: VarId, value: Value) -> String {
        let (_, f) = self.field(var);
        match &f.ty {
            MTy::Enum { ty, idents } => format!("{ty}::{}", idents[usize::from(value.0)]),
            MTy::Bool => (value.0 != 0).to_string(),
            MTy::Key { .. } => unreachable!("a key is compared with a row, not a literal"),
        }
    }
}

/// What this version covers, as reasons a model is outside it.
fn scope(ts: &TransitionSystem, domain: &DomainModel, why: &mut Vec<String>) {
    for v in ts.var_ids() {
        let var = ts.var(v);
        let entity = |e: EntId| ts.entity(e).id.clone();
        match &var.kind {
            VarKind::Exists(_) => {}
            VarKind::Column {
                entity: e,
                column,
                variation,
                ..
            } => {
                if *variation {
                    why.push(format!("{}.{column}: a variation column is chosen by the actor (choices are not covered)", entity(*e)));
                }
                match &var.domain {
                    Domain::Enum(_) | Domain::Bool => {}
                    Domain::Int | Domain::NullableInt => why.push(format!(
                        "{}.{column}: Int columns are not covered",
                        entity(*e)
                    )),
                    _ => why.push(format!(
                        "{}.{column}: nullable columns are not covered",
                        entity(*e)
                    )),
                }
            }
            VarKind::Owner { child, .. } => {
                if let Domain::Instance { optional: true, .. } = var.domain {
                    why.push(format!(
                        "{}: an optional key is not covered",
                        entity(*child)
                    ));
                }
            }
            VarKind::Prop { entity: e, key } => why.push(format!(
                "{}: the proposition {key} (drives) is not covered",
                entity(*e)
            )),
            VarKind::Run { usecase, .. } => why.push(format!(
                "{usecase}: run marks (use cases split into transactions) are not covered"
            )),
            VarKind::Raised { event, .. } => why.push(format!(
                "{event}: events (raises / triggers) are not covered"
            )),
            other => why.push(format!("{other:?}: not covered")),
        }
    }
    for e in ts.entity_ids() {
        let d = ts.entity(e);
        if d.birth != rdra_ish_core::lifecycle::Birth::Created {
            why.push(format!(
                "{}: no use case creates it (master data is not covered)",
                d.id
            ));
        }
    }
    for a in ts.actions() {
        let ActionOrigin::UseCase { step, .. } = &a.origin else {
            why.push(format!("{}: `now` and the clock are not covered", a.name));
            continue;
        };
        if step.is_some() {
            why.push(format!(
                "{}: use cases split into transactions are not covered",
                a.name
            ));
        }
        let mut seen = Vec::new();
        for p in &a.params {
            if seen.contains(&p.entity) {
                why.push(format!(
                    "{}: two rows of {} in one action are not covered",
                    a.name,
                    ts.entity(p.entity).id
                ));
            }
            seen.push(p.entity);
            if !matches!(
                p.role,
                rdra_ish_core::lifecycle::ParamRole::New
                    | rdra_ish_core::lifecycle::ParamRole::Existing
                    | rdra_ish_core::lifecycle::ParamRole::Parent { .. }
            ) {
                why.push(format!(
                    "{}: a row role {:?} is not covered",
                    a.name, p.role
                ));
            }
        }
        for g in &a.guards {
            match g.why {
                GuardWhy::TransitionFrom | GuardWhy::Owner | GuardWhy::Condition { .. } => {}
                GuardWhy::Clock => why.push(format!("{}: `now` is not covered", a.name)),
                GuardWhy::ArmCondition { .. } => why.push(format!(
                    "{}: a transition arm with `.when` (a choice) is not covered",
                    a.name
                )),
                GuardWhy::Restrict { .. } => why.push(format!(
                    "{}: deleting a row other rows name is not covered",
                    a.name
                )),
                other => why.push(format!("{}: a guard {other:?} is not covered", a.name)),
            }
            if g.reads_successor() {
                why.push(format!(
                    "{}: a condition on the row it creates is not covered",
                    a.name
                ));
            }
            if g.pred
                .terms()
                .any(|t| matches!(t, Term::Now | Term::Int(_)))
            {
                why.push(format!("{}: `now` and Int values are not covered", a.name));
            }
            nested(&g.pred, &a.name, why);
        }
        for eff in &a.effects {
            match eff {
                Effect::Create { .. } | Effect::Delete { .. } | Effect::Assign { .. } => {}
                Effect::Transition { arms, .. } => {
                    let mut froms: Vec<Value> = arms.iter().map(|a| a.from).collect();
                    froms.sort_by_key(|v| v.0);
                    let n = froms.len();
                    froms.dedup();
                    if froms.len() != n {
                        why.push(format!(
                            "{}: arms that share a `from` (a choice) are not covered",
                            a.name
                        ));
                    }
                }
                Effect::Choose { .. } => why.push(format!("{}: choices are not covered", a.name)),
                Effect::Tick => why.push(format!("{}: `now` is not covered", a.name)),
            }
        }
        // A created row's keys must be set: an unset one would name no row.
        for (k, p) in a.params.iter().enumerate() {
            if p.role != rdra_ish_core::lifecycle::ParamRole::New {
                continue;
            }
            for owner in &ts.entity(p.entity).owners {
                let set = a.effects.iter().any(|e| {
                    matches!(e, Effect::Assign { var, param, .. } if var == owner && usize::from(*param) == k)
                });
                if !set {
                    why.push(format!(
                        "{}: the created {} does not set its key",
                        a.name,
                        ts.entity(p.entity).id
                    ));
                }
            }
        }
        // A deleted row must be one no other row names.
        for eff in &a.effects {
            if let Effect::Delete { param } = eff {
                let e = a.params[usize::from(*param)].entity;
                let named = ts.var_ids().any(
                    |v| matches!(ts.var(v).kind, VarKind::Owner { parent, .. } if parent == e),
                );
                if named {
                    why.push(format!(
                        "{}: deleting a {} other rows name is not covered",
                        a.name,
                        ts.entity(e).id
                    ));
                }
            }
        }
    }
    for inv in ts.invariants() {
        if inv
            .body
            .terms()
            .any(|t| matches!(t, Term::Now | Term::Int(_)))
        {
            why.push(format!(
                "{}: `now` and Int values are not covered",
                inv.name
            ));
        }
        nested(&inv.body, &inv.name, why);
    }
    for f in &domain.fns {
        if !f.marks_in.is_empty() || !f.marks_out.is_empty() || f.step.is_some() {
            why.push(format!("{}: run marks are not covered", f.name));
        }
        if !f.raises.is_empty() || f.event_in.is_some() {
            why.push(format!("{}: events are not covered", f.name));
        }
        if !f.chosen.is_empty() {
            why.push(format!("{}: choices are not covered", f.name));
        }
        for i in &f.inputs {
            match &i.ty {
                InputType::Value(FieldType::Id(_)) if !i.nullable => {}
                InputType::Rows(_) => {}
                _ => why.push(format!(
                    "{}: the input {} is not covered (only ids of created rows and related rows are)",
                    f.name, i.name
                )),
            }
        }
    }
    for s in &domain.skipped {
        why.push(format!(
            "{}: no function is printed ({})",
            s.action, s.reason
        ));
    }
}

/// A quantifier inside a quantifier is not covered.
fn nested(p: &Pred, name: &str, why: &mut Vec<String>) {
    fn inner(p: &Pred) -> bool {
        p.nodes().skip(1).any(|n| {
            matches!(
                n,
                Pred::Forall { .. } | Pred::Exists { .. } | Pred::Count { .. }
            )
        })
    }
    for n in p.nodes() {
        if let Pred::Forall { body, .. } | Pred::Exists { body, .. } | Pred::Count { body, .. } = n
        {
            if inner(body)
                || matches!(
                    **body,
                    Pred::Forall { .. } | Pred::Exists { .. } | Pred::Count { .. }
                )
            {
                why.push(format!(
                    "{name}: a quantifier inside a quantifier is not covered"
                ));
            }
        }
    }
}

/// The entity `eid` with its names and fields, or why it is not covered.
fn ent(ts: &TransitionSystem, domain: &DomainModel, eid: EntId) -> Result<Ent, Vec<String>> {
    let d = ts.entity(eid);
    let mut why = Vec::new();
    let id_ty = domain
        .ids
        .iter()
        .find(|i| i.entity == d.id)
        .map(|i| i.name.clone());
    let Some(id_ty) = id_ty else {
        return Err(vec![format!(
            "{}: an entity with no one-column id is not covered",
            d.id
        )]);
    };
    let sum = domain.sums.iter().find(|s| s.entity == d.id);
    let record = domain.records.iter().find(|r| r.id == d.id);
    let (row, row_fields) = match (sum, record) {
        (Some(s), _) => (s.row.clone(), s.row_fields.clone()),
        (None, Some(r)) => (r.name.clone(), r.fields.clone()),
        (None, None) => return Err(vec![format!("{}: no type is printed for it", d.id)]),
    };
    for f in &row_fields {
        let ok = !f.nullable
            && matches!(
                &f.ty,
                FieldType::Enum(_) | FieldType::Id(_) | FieldType::Scalar(super::ir::Scalar::Bool)
            );
        if !ok {
            why.push(format!(
                "{}.{}: only Enum, Bool and key columns are covered",
                d.id, f.wire
            ));
        }
    }
    let mut fields = Vec::new();
    for v in ts.var_ids() {
        let var = ts.var(v);
        match &var.kind {
            VarKind::Column { entity, column, .. } if *entity == eid => {
                let Some(f) = row_fields.iter().find(|f| f.wire == *column) else {
                    why.push(format!("{}.{column}: no field in {row}", d.id));
                    continue;
                };
                let ty = match (&var.domain, &f.ty) {
                    (Domain::Enum(names), FieldType::Enum(ty)) => {
                        let decl = domain.enums.iter().find(|e| e.name == *ty);
                        let idents: Option<Vec<String>> = names
                            .iter()
                            .map(|n| {
                                decl.and_then(|d| d.values.iter().find(|v| v.wire == *n))
                                    .map(|v| v.ident.clone())
                            })
                            .collect();
                        match idents {
                            Some(idents) => MTy::Enum {
                                ty: ty.clone(),
                                idents,
                            },
                            None => {
                                why.push(format!(
                                    "{}.{column}: its values do not match {ty}",
                                    d.id
                                ));
                                continue;
                            }
                        }
                    }
                    (Domain::Bool, FieldType::Scalar(super::ir::Scalar::Bool)) => MTy::Bool,
                    _ => continue, // refused by the scope check
                };
                let tag = sum.is_some_and(|s| s.tag.wire == *column);
                fields.push(MField {
                    var: v,
                    name: f.name.clone(),
                    ty,
                    tag,
                });
            }
            VarKind::Owner { child, parent, .. } if *child == eid => {
                let pid = &ts.entity(*parent).id;
                let parent_ty = domain
                    .ids
                    .iter()
                    .find(|i| i.entity == *pid)
                    .map(|i| i.name.clone());
                let keys: Vec<_> = row_fields
                    .iter()
                    .filter(|f| {
                        f.wire != "id"
                            && Some(&f.ty)
                                == parent_ty
                                    .as_ref()
                                    .map(|t| FieldType::Id(t.clone()))
                                    .as_ref()
                    })
                    .collect();
                if keys.len() != 1 {
                    why.push(format!(
                        "{}: {} keys to {pid}; exactly one is covered",
                        d.id,
                        keys.len()
                    ));
                    continue;
                }
                fields.push(MField {
                    var: v,
                    name: keys[0].name.clone(),
                    ty: MTy::Key { parent: *parent },
                    tag: false,
                });
            }
            _ => {}
        }
    }
    let sum = sum.map(|s| {
        let idents: Vec<String> = s.variants.iter().map(|v| v.value.ident.clone()).collect();
        Sum {
            name: s.name.clone(),
            tag_field: s.tag.name.clone(),
            variants: s
                .variants
                .iter()
                .map(|v| v.name.clone())
                .zip(idents)
                .collect(),
            wires: s.variants.iter().map(|v| v.value.wire.clone()).collect(),
        }
    });
    if let Some(s) = &sum {
        if !fields.iter().any(|f| f.tag) {
            why.push(format!(
                "{}: its state column {} is not tracked",
                d.id, s.tag_field
            ));
        }
    }
    if !why.is_empty() {
        return Err(why);
    }
    Ok(Ent {
        eid,
        id: d.id.clone(),
        snake: snake(&d.id),
        m: format!("{}M", d.id),
        id_ty,
        row,
        sum,
        fields,
    })
}
