/// camelCase of a PascalCase name.
pub(crate) fn camel(pascal: &str) -> String {
    let mut chars = pascal.chars();
    match chars.next() {
        Some(c) => c.to_lowercase().chain(chars).collect(),
        None => String::new(),
    }
}
