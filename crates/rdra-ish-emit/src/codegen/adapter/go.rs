//! The Go model adapter: `ModelState`, `Call`, `ModelAdapter`, `SplitAdapter` and `Conform`,
//! in a package of its own so its names meet no name of the domain code.

use super::super::conformance::{TRACES_ENV, TRACES_FORMAT};
use super::super::go::{comment, doc, struct_decl, Line};
use super::super::go_port::CONFORMANCE_TEST;
use super::super::{string_literal, type_ident};
use super::{AdColumn, Adapter, ArgKind, RowToken, Val, REPORT};

pub(super) fn print(a: &Adapter, header: &[String], package: &str) -> String {
    let mut out = String::new();
    out.push_str("// Code generated by rdra-ish codegen. DO NOT EDIT.\n//\n");
    for line in header {
        out.push_str(&comment(line, ""));
    }
    out.push('\n');
    out.push_str(&format!(
        "// Package {package} is the model adapter of the conformance traces.\npackage {package}\n\n"
    ));
    out.push_str(
        "import (\n\t\"errors\"\n\t\"fmt\"\n\t\"sort\"\n\t\"strconv\"\n\t\"strings\"\n)\n\n",
    );
    print_enums(a, &mut out);
    print_state(a, &mut out);
    print_calls(a, &mut out);
    print_adapter(&mut out);
    print_conform(&mut out);
    print_seed_rows(a, &mut out);
    print_call_parser(a, &mut out);
    print_abstraction(a, &mut out);
    while out.ends_with('\n') {
        out.pop();
    }
    out
}

fn ty(a: &Adapter, val: Val) -> String {
    match val {
        Val::Int => "int64".to_string(),
        Val::Bool => "bool".to_string(),
        Val::Text => "string".to_string(),
        Val::Enum(i) => a.enums[i].name.clone(),
    }
}

fn column_ty(a: &Adapter, c: &AdColumn) -> String {
    let t = ty(a, c.val);
    if c.nullable {
        format!("*{t}")
    } else {
        t
    }
}

/// An exported field name.
fn field(name: &str) -> String {
    type_ident(name)
}

/// The field of a call's argument: a call struct has the method `Action`, so an argument whose
/// field would be `Action` gets a suffix.
fn arg_field(name: &str) -> String {
    let f = field(name);
    if f == "Action" {
        format!("{f}Arg")
    } else {
        f
    }
}

fn print_enums(a: &Adapter, out: &mut String) {
    for e in &a.enums {
        out.push_str(&doc(
            &e.name,
            &["is a value of the model, as the model spells it.".to_string()],
            "",
        ));
        out.push_str(&format!("type {} string\n\n", e.name));
        out.push_str(&format!("// The values of {}.\nconst (\n", e.name));
        let lines: Vec<Line> = e
            .values
            .iter()
            .map(|(wire, id)| {
                Line::Cells(vec![
                    format!("{}{}", e.name, type_ident(id)),
                    e.name.clone(),
                    format!("= {}", string_literal(wire)),
                ])
            })
            .collect();
        out.push_str(&super::super::go::block(&lines));
        out.push_str(")\n\n");
        out.push_str(&format!(
            "// Valid reports whether v is a value of {}.\nfunc (v {}) Valid() bool {{\n\tswitch v {{\n\tcase {}:\n\t\treturn true\n\t}}\n\treturn false\n}}\n\n",
            e.name,
            e.name,
            e.values
                .iter()
                .map(|(_, id)| format!("{}{}", e.name, type_ident(id)))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
}

fn print_state(a: &Adapter, out: &mut String) {
    for e in &a.entities {
        out.push_str(&doc(
            &e.name,
            &[format!(
                "is a {} row as the model sees it: its id and the columns the model tracks. The adapter picks the other columns' values when it seeds.",
                e.entity
            )],
            "",
        ));
        let mut lines = vec![
            Line::Comment(format!("The primary key `{}`.", e.id.wire)),
            Line::Cells(vec![field(&e.id.wire), column_ty(a, &e.id)]),
        ];
        for c in &e.tracked {
            lines.push(Line::Comment(if c.presence {
                format!("Whether `{}` is set: the model tracks only that.", c.wire)
            } else if c.nullable {
                format!("`{}`; nil for null.", c.wire)
            } else {
                format!("`{}`.", c.wire)
            }));
            lines.push(Line::Cells(vec![field(&c.wire), column_ty(a, c)]));
        }
        out.push_str(&struct_decl(&e.name, &lines));
    }
    for r in &a.runs {
        out.push_str(&doc(
            &r.name,
            &[format!(
                "is a pending run mark of {} on a {} row: the last step of the run that wrote the row.",
                r.usecase, r.entity
            )],
            "",
        ));
        out.push_str(&struct_decl(
            &r.name,
            &[
                Line::Cells(vec!["Id".to_string(), ty(a, r.id)]),
                Line::Cells(vec!["Step".to_string(), "int".to_string()]),
            ],
        ));
    }
    for ev in &a.events {
        out.push_str(&doc(
            &ev.name,
            &[format!(
                "is the payload of a {} event: the ids of the rows it was raised on.",
                ev.ty
            )],
            "",
        ));
        let lines: Vec<Line> = ev
            .ids
            .iter()
            .map(|(name, _, val, _)| Line::Cells(vec![field(name), ty(a, *val)]))
            .collect();
        out.push_str(&struct_decl(&ev.name, &lines));
        if ev.field.is_some() {
            out.push_str(&doc(
                &ev.raised,
                &[format!(
                    "is a raise of {} the model remembers: the ids of the rows a triggered use case reads.",
                    ev.ty
                )],
                "",
            ));
            let lines: Vec<Line> = ev
                .ids
                .iter()
                .filter(|(_, _, _, tracked)| *tracked)
                .map(|(name, _, val, _)| Line::Cells(vec![field(name), ty(a, *val)]))
                .collect();
            out.push_str(&struct_decl(&ev.raised, &lines));
        }
    }
    out.push_str("// ModelState is everything a store holds, as the model sees it: the rows of each entity, the\n// pending run marks, and the raises a triggered use case reads. The order of a list does not\n// matter.\n");
    let mut lines = Vec::new();
    for e in &a.entities {
        lines.push(Line::Cells(vec![
            type_ident(&e.entity),
            format!("[]{}", e.name),
        ]));
    }
    for r in &a.runs {
        lines.push(Line::Cells(vec![
            format!("{}s", r.name),
            format!("[]{}", r.name),
        ]));
    }
    for ev in &a.events {
        if ev.field.is_some() {
            lines.push(Line::Cells(vec![
                type_ident(&ev.ty),
                format!("[]{}", ev.raised),
            ]));
        }
    }
    out.push_str(&struct_decl("ModelState", &lines));
}

fn print_calls(a: &Adapter, out: &mut String) {
    out.push_str("// Call is one call of a use case: the ids of its rows and run marks, its event, its inputs\n// and its choices, as the traces give them. Each action has a struct of its own.\ntype Call interface {\n\t// Action is the action, as the model names it.\n\tAction() string\n}\n\n");
    for c in &a.calls {
        out.push_str(&doc(
            &c.name,
            &[format!(
                "is the action {} of the use case {}.",
                c.action, c.usecase
            )],
            "",
        ));
        let lines: Vec<Line> = c
            .args
            .iter()
            .map(|arg| {
                let t = match &arg.kind {
                    ArgKind::Value { val, nullable } => {
                        let t = ty(a, *val);
                        if *nullable {
                            format!("*{t}")
                        } else {
                            t
                        }
                    }
                    ArgKind::Event(i) => a.events[*i].name.clone(),
                };
                Line::Cells(vec![arg_field(&arg.name), t])
            })
            .collect();
        out.push_str(&struct_decl(&c.name, &lines));
        out.push_str(&format!(
            "// Action is {}.\nfunc ({}) Action() string {{\n\treturn {}\n}}\n\n",
            string_literal(&c.action),
            c.name,
            string_literal(&c.action)
        ));
    }
}

fn print_adapter(out: &mut String) {
    out.push_str(&format!(
        r#"// Outcome is what a call did: it ran, or the kind of refusal, with the store unchanged.
type Outcome int

const (
	// Ran is a call that ran.
	Ran Outcome = iota
	// NotEnabled is a call that does not run from its rows' states, names a row that does not
	// exist, or a commit whose rows changed since its prepare.
	NotEnabled
	// Rejected is a call a condition the model applies to the use case rejects.
	Rejected
	// InvalidArgument is a call with an argument that breaks what the verified model keeps.
	InvalidArgument
)

// String is the outcome in words.
// adKinds is the outcome of each kind of refusal, as the traces spell it.
var adKinds = map[string]Outcome{{"NotEnabled": NotEnabled, "Rejected": Rejected, "InvalidArgument": InvalidArgument}}

func (o Outcome) String() string {{
	switch o {{
	case Ran:
		return "ran"
	case NotEnabled:
		return "not enabled"
	case Rejected:
		return "rejected"
	case InvalidArgument:
		return "invalid argument"
	}}
	return "unknown outcome " + strconv.Itoa(int(o))
}}

// ModelAdapter is what a service offers the conformance harness: a store it can empty, seed
// and read back as the model sees it, and its use cases by call. It uses no type of the
// generated domain code, so the service may be written, renamed and restructured freely.
type ModelAdapter interface {{
	// Reset empties the store: a trace starts here.
	Reset()
	// Seed stores these rows in the empty store, with a value of the adapter's choosing for
	// each column the model does not track.
	Seed(state ModelState)
	// Observe returns what the store holds now, as the model sees it.
	Observe() ModelState
	// Invoke makes the call in one transaction: Ran, or why it did not run, with the store
	// unchanged.
	Invoke(call Call) Outcome
}}

// SplitAdapter is a ModelAdapter that also splits a call in two, for the interleaved rows
// of the traces. The harness runs those rows of an adapter that is not one as plain calls
// and counts them as skipped, so conditional writes go unchecked.
type SplitAdapter interface {{
	ModelAdapter
	// Prepare reads the call's rows and holds its write for Commit, writing nothing: Ran,
	// or why the call does not run.
	Prepare(call Call) Outcome
	// Commit stores the write Prepare holds in one transaction, only where its rows are
	// still what the prepare read: Ran, or why it did not.
	Commit() Outcome
}}

// AdapterReport is what Conform checked.
type AdapterReport struct {{
	Traces        int
	Calls         int
	Refusals      int
	Interleavings int
	// Skipped counts the interleaved rows run as plain calls: the adapter is no SplitAdapter.
	Skipped int
	// Split counts the calls and refused calls made again by Prepare and then Commit: none
	// when the adapter is no SplitAdapter.
	Split int
}}

// Line is the line a conformance test prints on a pass, which `check --code=run` reads.
func (r AdapterReport) Line() string {{
	return fmt.Sprintf({line}, r.Traces, r.Calls, r.Refusals, r.Interleavings, r.Skipped, r.Split)
}}

"#,
        line = string_literal(&format!(
            "{REPORT}%d traces, %d calls, %d refusals, %d interleavings, %d interleavings skipped, %d split calls"
        )),
    ));
}

fn print_conform(out: &mut String) {
    out.push_str(&format!(
        r##"// Conform drives adapter along traces (the file `codegen --conformance` writes): it resets and
// seeds each trace's initial state, makes each call, and after each compares what the store
// holds with the state the model reaches. A call the model refuses must be refused, with the
// kind the traces name, and change nothing, and so must a commit whose rows another call
// changed after its prepare. A SplitAdapter runs the traces again with each call made by
// Prepare and then Commit. It returns the first difference.
func Conform(adapter ModelAdapter, traces string) (AdapterReport, error) {{
	report, err := adPass(adapter, traces, false)
	if err != nil {{
		return report, err
	}}
	if _, ok := adapter.(SplitAdapter); ok {{
		again, err := adPass(adapter, traces, true)
		if err != nil {{
			return report, err
		}}
		report.Split = again.Calls + again.Refusals
	}}
	return report, nil
}}

// adRun makes call: by Invoke, or, with split, by the adapter's Prepare and then its Commit.
func adRun(adapter ModelAdapter, c Call, split bool) Outcome {{
	if s, ok := adapter.(SplitAdapter); ok && split {{
		if o := s.Prepare(c); o != Ran {{
			return o
		}}
		return s.Commit()
	}}
	return adapter.Invoke(c)
}}

// adPass is one run of traces, with each call made by adRun.
func adPass(adapter ModelAdapter, traces string, viaSplit bool) (AdapterReport, error) {{
	var report AdapterReport
	how := ""
	if viaSplit {{
		how = " through prepare and commit"
	}}
	lines := strings.Split(traces, "\n")
	if len(lines) == 0 || strings.TrimRight(lines[0], "\r ") != {format} {{
		return report, errors.New("not a traces file of this version: generate the adapter and the traces again")
	}}
	split, canSplit := adapter.(SplitAdapter)
	states := map[string][]string{{}}
	defining := ""
	inTrace := false
	var seed ModelState
	var want []string
	for n, line := range lines[1:] {{
		at := func(err error) error {{ return fmt.Errorf("traces line %d: %w", n+2, err) }}
		toks := strings.Fields(line)
		if len(toks) == 0 {{
			continue
		}}
		rest := toks[1:]
		state := func(i int) ([]string, error) {{
			if i < len(rest) {{
				if s, ok := states[rest[i]]; ok {{
					return s, nil
				}}
			}}
			return nil, at(errors.New("names no state defined above"))
		}}
		switch toks[0] {{
		case "G", "C", "X", "I":
			if !inTrace {{
				return report, at(errors.New("a call outside a trace"))
			}}
		}}
		switch toks[0] {{
		case "#":
		case "S":
			if len(rest) == 0 {{
				return report, at(errors.New("a state without a number"))
			}}
			defining = rest[0]
			states[defining] = []string{{}}
		case "A":
			states[defining] = append(states[defining], strings.Join(rest, " "))
		case "T":
			s, err := state(0)
			if err != nil {{
				return report, err
			}}
			want = s
			adapter.Reset()
			inTrace = true
			seed = ModelState{{}}
			report.Traces++
		case "R":
			if err := adSeedRow(&seed, rest); err != nil {{
				return report, at(err)
			}}
		case "G":
			adapter.Seed(seed)
			seed = ModelState{{}}
			if err := adCompare(adAbstract(adapter.Observe()), want, "after seeding the initial state"); err != nil {{
				return report, at(err)
			}}
		case "C":
			next, err := state(0)
			if err != nil {{
				return report, err
			}}
			call := rest[1:]
			c, err := adCall(call)
			if err != nil {{
				return report, at(err)
			}}
			if o := adRun(adapter, c, viaSplit); o != Ran {{
				return report, at(fmt.Errorf("the model runs `%s` here, and the service refused it%s: %v", strings.Join(call, " "), how, o))
			}}
			if err := adCompare(adAbstract(adapter.Observe()), next, "after `"+strings.Join(call, " ")+"`"); err != nil {{
				return report, at(err)
			}}
			want = next
			report.Calls++
		case "X":
			if len(rest) < 1 {{
				return report, at(errors.New("a refused call without its kind"))
			}}
			kind, rest := rest[0], rest[1:]
			c, err := adCall(rest)
			if err != nil {{
				return report, at(err)
			}}
			o := adRun(adapter, c, viaSplit)
			if o == Ran {{
				return report, at(fmt.Errorf("the model refuses `%s` here, and the service ran it%s", strings.Join(rest, " "), how))
			}}
			if kind != "-" && adKinds[kind] != o {{
				return report, at(fmt.Errorf("the model refuses `%s` here with %s, and the service refused it with %v", strings.Join(rest, " "), kind, o))
			}}
			if err := adCompare(adAbstract(adapter.Observe()), want, "after the refused `"+strings.Join(rest, " ")+"`"); err != nil {{
				return report, at(err)
			}}
			report.Refusals++
		case "I":
			next, err := state(0)
			if err != nil {{
				return report, err
			}}
			bar := -1
			for i, t := range rest {{
				if t == "|" {{
					bar = i
					break
				}}
			}}
			if bar < 1 {{
				return report, at(errors.New("an interleaving without `|`"))
			}}
			first, second := rest[1:bar], rest[bar+1:]
			early, err := adCall(first)
			if err != nil {{
				return report, at(err)
			}}
			late, err := adCall(second)
			if err != nil {{
				return report, at(err)
			}}
			if canSplit {{
				if o := split.Prepare(early); o != Ran {{
					return report, at(fmt.Errorf("the model runs `%s` here, and the service refused it: %v", strings.Join(first, " "), o))
				}}
			}}
			if o := adapter.Invoke(late); o != Ran {{
				return report, at(fmt.Errorf("the model runs `%s` here, and the service refused it: %v", strings.Join(second, " "), o))
			}}
			if err := adCompare(adAbstract(adapter.Observe()), next, "after `"+strings.Join(second, " ")+"`"); err != nil {{
				return report, at(err)
			}}
			if canSplit {{
				if split.Commit() == Ran {{
					return report, at(fmt.Errorf("the service committed `%s`, prepared before `%s` changed a row it writes: the write must be conditional on what the row was", strings.Join(first, " "), strings.Join(second, " ")))
				}}
				if err := adCompare(adAbstract(adapter.Observe()), next, "after the refused commit of `"+strings.Join(first, " ")+"`"); err != nil {{
					return report, at(err)
				}}
				report.Interleavings++
			}} else {{
				report.Skipped++
			}}
			want = next
		default:
			return report, at(fmt.Errorf("unknown record %s", toks[0]))
		}}
	}}
	return report, nil
}}

// adCompare reports every line the store and the model's state do not share.
func adCompare(got, want []string, when string) error {{
	if strings.Join(got, "\n") == strings.Join(want, "\n") {{
		return nil
	}}
	has := func(lines []string, line string) bool {{
		for _, l := range lines {{
			if l == line {{
				return true
			}}
		}}
		return false
	}}
	out := when + ", the store differs from the model:"
	for _, l := range want {{
		if !has(got, l) {{
			out += "\n  model only: " + l
		}}
	}}
	for _, l := range got {{
		if !has(want, l) {{
			out += "\n  store only: " + l
		}}
	}}
	return errors.New(out)
}}

// adArgs reads the values of a trace record; the first error sticks.
type adArgs struct {{
	toks []string
	err  error
}}

func (a *adArgs) next() string {{
	if len(a.toks) == 0 {{
		if a.err == nil {{
			a.err = errors.New("too few values")
		}}
		return "~"
	}}
	t := a.toks[0]
	a.toks = a.toks[1:]
	return t
}}

func (a *adArgs) int(t string) int64 {{
	n, err := strconv.ParseInt(t, 10, 64)
	if err != nil && a.err == nil {{
		a.err = err
	}}
	return n
}}

func (a *adArgs) bool(t string) bool {{
	b, err := strconv.ParseBool(t)
	if err != nil && a.err == nil {{
		a.err = err
	}}
	return b
}}

func adEnum[T interface{{ Valid() bool }}](a *adArgs, v T) T {{
	if !v.Valid() && a.err == nil {{
		a.err = fmt.Errorf("not a value: %v", v)
	}}
	return v
}}

func adOpt[T any](t string, f func(string) T) *T {{
	if t == "~" {{
		return nil
	}}
	v := f(t)
	return &v
}}

func adText[T any](p *T) string {{
	if p == nil {{
		return "~"
	}}
	return fmt.Sprint(*p)
}}

func adSet(set bool) string {{
	if set {{
		return "+"
	}}
	return "~"
}}

"##,
        format = string_literal(TRACES_FORMAT),
    ));
}

/// An expression that reads the next token of `a` as `val`.
fn read(ad: &Adapter, val: Val, nullable: bool, presence: bool) -> String {
    let value = |t: &str| match val {
        _ if presence => format!("{t} != \"~\""),
        Val::Int => format!("a.int({t})"),
        Val::Bool => format!("a.bool({t})"),
        Val::Text => t.to_string(),
        Val::Enum(i) => format!("adEnum(a, {}({t}))", ad.enums[i].name),
    };
    if nullable {
        format!(
            "adOpt(a.next(), func(t string) {} {{ return {} }})",
            ty(ad, val),
            value("t")
        )
    } else {
        value("a.next()")
    }
}

fn print_seed_rows(ad: &Adapter, out: &mut String) {
    out.push_str("func adSeedRow(seed *ModelState, toks []string) error {\n\tif len(toks) == 0 {\n\t\treturn errors.New(\"a row names no entity\")\n\t}\n\ta := &adArgs{toks: toks[1:]}\n\tswitch toks[0] {\n");
    for e in &ad.entities {
        out.push_str(&format!(
            "\tcase {}:\n\t\trow := {}{{}}\n",
            string_literal(&e.entity),
            e.name
        ));
        for token in &e.tokens {
            match token {
                RowToken::Id => out.push_str(&format!(
                    "\t\trow.{} = {}\n",
                    field(&e.id.wire),
                    read(ad, e.id.val, false, false)
                )),
                RowToken::Tracked(i) => {
                    let c = &e.tracked[*i];
                    out.push_str(&format!(
                        "\t\trow.{} = {}\n",
                        field(&c.wire),
                        read(ad, c.val, c.nullable, c.presence)
                    ));
                }
                RowToken::Skip => out.push_str("\t\ta.next()\n"),
            }
        }
        out.push_str(&format!(
            "\t\tseed.{0} = append(seed.{0}, row)\n",
            type_ident(&e.entity)
        ));
    }
    out.push_str("\tdefault:\n\t\treturn fmt.Errorf(\"no entity %s in this adapter\", toks[0])\n\t}\n\treturn a.err\n}\n\n");
}

fn print_call_parser(ad: &Adapter, out: &mut String) {
    // A model whose every action is an entry point has no call: the harness names none.
    if ad.calls.is_empty() {
        out.push_str("func adCall(call []string) (Call, error) {\n\tif len(call) == 0 {\n\t\treturn nil, errors.New(\"a call names no use case\")\n\t}\n\treturn nil, fmt.Errorf(\"no use case %s in this adapter\", call[0])\n}\n\n");
        return;
    }
    out.push_str("func adCall(call []string) (Call, error) {\n\tif len(call) == 0 {\n\t\treturn nil, errors.New(\"a call names no use case\")\n\t}\n\ta := &adArgs{toks: call[1:]}\n\tvar c Call\n\tswitch call[0] {\n");
    for c in &ad.calls {
        out.push_str(&format!(
            "\tcase {}:\n\t\tv := {}{{}}\n",
            string_literal(&c.action),
            c.name
        ));
        for arg in &c.args {
            match &arg.kind {
                ArgKind::Value { val, nullable } => out.push_str(&format!(
                    "\t\tv.{} = {}\n",
                    arg_field(&arg.name),
                    read(ad, *val, *nullable, false)
                )),
                ArgKind::Event(i) => {
                    for (name, _, val, _) in &ad.events[*i].ids {
                        out.push_str(&format!(
                            "\t\tv.{}.{} = {}\n",
                            arg_field(&arg.name),
                            field(name),
                            read(ad, *val, false, false)
                        ));
                    }
                }
            }
        }
        out.push_str("\t\tc = v\n");
    }
    out.push_str("\tdefault:\n\t\treturn nil, fmt.Errorf(\"no use case %s in this adapter\", call[0])\n\t}\n\treturn c, a.err\n}\n\n");
}

/// A tracked column of `row`, as the traces spell it.
fn abstracted(c: &AdColumn) -> String {
    let place = format!("row.{}", field(&c.wire));
    if c.presence {
        format!("adSet({place})")
    } else if c.nullable {
        format!("adText({place})")
    } else {
        format!("fmt.Sprint({place})")
    }
}

fn print_abstraction(ad: &Adapter, out: &mut String) {
    out.push_str("// adAbstract is the state as the traces spell it: one line per row with the columns the\n// model tracks, per pending run mark, and per raise a triggered use case reads; sorted.\nfunc adAbstract(s ModelState) []string {\n\tout := []string{}\n");
    for e in &ad.entities {
        out.push_str(&format!(
            "\tfor _, row := range s.{} {{\n\t\tline := {} + fmt.Sprint(row.{})\n",
            type_ident(&e.entity),
            string_literal(&format!("{} ", e.entity)),
            field(&e.id.wire)
        ));
        for c in &e.tracked {
            out.push_str(&format!(
                "\t\tline += {} + {}\n",
                string_literal(&format!(" {}=", c.wire)),
                abstracted(c)
            ));
        }
        out.push_str("\t\tout = append(out, line)\n\t}\n");
    }
    for r in &ad.runs {
        out.push_str(&format!(
            "\tfor _, m := range s.{}s {{\n\t\tout = append(out, fmt.Sprintf({}, m.Id, m.Step))\n\t}}\n",
            r.name,
            string_literal(&format!("mark {} {} %v %d", r.usecase, r.entity))
        ));
    }
    for ev in &ad.events {
        if ev.field.is_none() {
            continue;
        }
        out.push_str(&format!(
            "\tfor _, ev := range s.{} {{\n",
            type_ident(&ev.ty)
        ));
        for (name, entity, _, tracked) in &ev.ids {
            if *tracked {
                out.push_str(&format!(
                    "\t\tout = append(out, fmt.Sprintf({}, ev.{}))\n",
                    string_literal(&format!("raised {} {entity} %v", ev.ty)),
                    field(name)
                ));
            }
        }
        out.push_str("\t}\n");
    }
    out.push_str("\tsort.Strings(out)\n\tdedup := out[:0]\n\tfor i, l := range out {\n\t\tif i == 0 || l != out[i-1] {\n\t\t\tdedup = append(dedup, l)\n\t\t}\n\t}\n\treturn dedup\n}\n");
}

/// The adapter probe: a `_test.go` file in the adapter's package (or one importing it) whose
/// test drives the adapter `new` makes along the traces, and logs what it ran.
pub(super) fn probe(
    binding: &super::super::ProbeBinding,
    new: &str,
    traces: &str,
) -> Option<super::super::probe::Probe> {
    let (svc_import, ty) = binding
        .service
        .rsplit_once('.')
        .filter(|(_, ty)| !ty.contains('/'))?;
    let qualifier = |path: &str| {
        path.rsplit('/')
            .next()
            .unwrap_or(path)
            .chars()
            .map(|c| if c.is_alphanumeric() { c } else { '_' })
            .collect::<String>()
    };
    let adp = binding
        .package
        .clone()
        .unwrap_or_else(|| qualifier(&binding.module));
    let same = binding.module == svc_import;
    let svc = if same {
        adp.clone()
    } else {
        qualifier(svc_import)
    };
    let mut w = super::super::probe::ProbeWriter::new(
        "// Code generated by rdra-ish codegen. DO NOT EDIT.",
    );
    w.line(&format!(
        "//\n// The adapter probe of `rdra-ish check --code`: *{svc}.{ty} implements the model adapter, and\n// {CONFORMANCE_TEST} drives it along the model's traces ({traces}). `check --code=run` runs it;\n// `rdra-ish codegen --code` writes it again.\n\npackage {svc}_test\n"
    ));
    let mut imports = String::from("import (\n\t\"os\"\n\t\"testing\"\n\n");
    let adp_spec = (!same).then(|| (binding.module.as_str(), format!("{adp} ")));
    imports.push_str(&super::super::go::import_group(
        adp_spec.into_iter().chain([(svc_import, String::new())]),
    ));
    w.line(&imports);
    w.line(&format!("var _ {adp}.ModelAdapter = (*{svc}.{ty})(nil)\n"));
    w.line(&format!(
        "// {CONFORMANCE_TEST} drives the adapter along the model's traces and logs what it ran.\nfunc {CONFORMANCE_TEST}(t *testing.T) {{\n\tpath := {}\n\tif substitute := os.Getenv(\"{TRACES_ENV}\"); substitute != \"\" {{\n\t\tpath = substitute\n\t}}\n\ttraces, err := os.ReadFile(path)\n\tif err != nil {{\n\t\tt.Fatal(err)\n\t}}\n\treport, err := {adp}.Conform({new}, string(traces))\n\tif err != nil {{\n\t\tt.Fatal(\"rdra-ish conformance: \" + err.Error())\n\t}}\n\tt.Log(report.Line())\n}}",
        string_literal(traces)
    ));
    let mut probe = w.finish();
    while probe.text.ends_with('\n') {
        probe.text.pop();
    }
    Some(probe)
}
