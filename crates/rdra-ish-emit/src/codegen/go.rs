//! The Go printer, in the shapes of docs/design/algebraic-codegen.md, "Generated code style":
//! defined types with `Parse<Type>` for ids, scalars and value sets; a state type as a sealed
//! interface whose states are interfaces too, each implemented by one unexported struct, so
//! only this package makes a state; `<Entity>Row` with the tag column, and `<Entity>FromRow`,
//! which checks it; transition functions that return new values or a `*<UseCase>Error`. No
//! generated code calls `panic`, and the output is what `gofmt` prints.

use std::collections::BTreeSet;

use super::ir::{DomainModel, Field, FieldType, FnDecl, RecordKind, Scalar, SumDecl, VariantDecl};
use super::{header_lines, obligation_lines, one_line, string_literal, Options};

pub(super) fn print(
    domain: &DomainModel,
    options: &Options,
    traces: Option<&super::conformance::Traces>,
) -> String {
    let mut out = String::new();
    // The first line marks the file as generated (`go vet` and linters know it), and the header
    // is no doc comment, so `gofmt` keeps it as written: a blank line parts it from the package.
    out.push_str("// Code generated by rdra-ish codegen. DO NOT EDIT.\n//\n");
    let mut head = header_lines(options);
    head.push(String::new());
    head.extend(obligation_lines(domain));
    head.extend(super::conformance_lines(
        domain,
        traces,
        "Conform",
        "ConformancePort",
    ));
    for line in head {
        out.push_str(&comment(&line, ""));
    }
    out.push('\n');
    out.push_str(&format!(
        "// Package {0} holds the domain types of the model.\npackage {0}\n\n",
        options.package
    ));

    let mut imports: BTreeSet<&str> = BTreeSet::new();
    if !domain.fns.is_empty() || !domain.sums.is_empty() {
        imports.insert("errors");
    }
    if domain.harness {
        imports.extend(super::go_port::IMPORTS);
    }
    if !imports.is_empty() {
        out.push_str("import (\n");
        for i in &imports {
            out.push_str(&format!("\t\"{i}\"\n"));
        }
        out.push_str(")\n\n");
    }

    print_scalars(&mut out);
    print_ids(domain, &mut out);
    print_enums(domain, &mut out);
    print_records(domain, &mut out);
    if !domain.fns.is_empty() || !domain.sums.is_empty() {
        print_error_details(&mut out);
    }
    for sum in &domain.sums {
        print_sum(domain, sum, &mut out);
    }
    print_functions(domain, &mut out);
    print_validators(domain, &mut out);
    print_rows(domain, &mut out);
    print_dispatchers(domain, &mut out);
    print_helpers(domain, &mut out);
    super::go_port::print_port(domain, &mut out);
    // `codegen` ends the file with one newline.
    while out.ends_with('\n') {
        out.pop();
    }
    out
}

// ── Layout ───────────────────────────────────────────────────────────────────

/// A line of a block whose columns `gofmt` aligns: a comment, which ends the alignment, or
/// cells (a field's name, type, and tag; a constant's name, type, and value).
pub(super) enum Line {
    Comment(String),
    Cells(Vec<String>),
}

/// The lines of a block, indented one tab, aligned as `gofmt` aligns them: a run of lines
/// with a cell after column `k` pads column `k` to its widest cell plus one space; a comment
/// line ends every run.
pub(super) fn block(lines: &[Line]) -> String {
    let mut out = String::new();
    let mut start = 0;
    while start < lines.len() {
        if let Line::Comment(text) = &lines[start] {
            out.push_str(&comment(text, "\t"));
            start += 1;
            continue;
        }
        let end = (start..lines.len())
            .find(|&i| matches!(lines[i], Line::Comment(_)))
            .unwrap_or(lines.len());
        let rows: Vec<&Vec<String>> = lines[start..end]
            .iter()
            .map(|l| match l {
                Line::Cells(c) => c,
                Line::Comment(_) => unreachable!("a section holds no comment"),
            })
            .collect();
        let widest = rows.iter().map(|r| r.len()).max().unwrap_or(0);
        let mut widths = vec![vec![0usize; widest]; rows.len()];
        for k in 0..widest {
            let mut i = 0;
            while i < rows.len() {
                if rows[i].len() <= k + 1 {
                    i += 1;
                    continue;
                }
                let run_end = (i..rows.len())
                    .find(|&j| rows[j].len() <= k + 1)
                    .unwrap_or(rows.len());
                let width = (i..run_end)
                    .map(|j| rows[j][k].chars().count())
                    .max()
                    .unwrap_or(0);
                for w in &mut widths[i..run_end] {
                    w[k] = width;
                }
                i = run_end;
            }
        }
        for (row, width) in rows.iter().zip(&widths) {
            out.push('\t');
            for (k, cell) in row.iter().enumerate() {
                out.push_str(cell);
                if k + 1 < row.len() {
                    let pad = width[k] - cell.chars().count() + 1;
                    out.push_str(&" ".repeat(pad));
                }
            }
            out.push('\n');
        }
        start = end;
    }
    out
}

/// `type <name> struct { .. }` over `lines`.
pub(super) fn struct_decl(name: &str, lines: &[Line]) -> String {
    if lines.is_empty() {
        return format!("type {name} struct{{}}\n\n");
    }
    format!("type {name} struct {{\n{}}}\n\n", block(lines))
}

/// A field line: its doc comments, then the name, the type, and the `json` tag when given.
fn field_lines(
    lines: &mut Vec<Line>,
    doc: &[String],
    name: String,
    ty: String,
    wire: Option<&str>,
) {
    for d in doc {
        lines.push(Line::Comment(one_line(d)));
    }
    let mut cells = vec![name, ty];
    if let Some(w) = wire {
        cells.push(format!("`json:{}`", string_literal(w)));
    }
    lines.push(Line::Cells(cells));
}

pub(super) fn field_type(ty: &FieldType) -> String {
    match ty {
        FieldType::Scalar(s) => scalar(*s).to_string(),
        FieldType::Enum(name) | FieldType::Id(name) => name.clone(),
        FieldType::Rows(name) => format!("[]{name}"),
    }
}

/// The type of a column or an input: a pointer when it is nullable.
fn value_type(ty: &FieldType, nullable: bool) -> String {
    let ty = field_type(ty);
    if nullable {
        format!("*{ty}")
    } else {
        ty
    }
}

pub(super) fn scalar(s: Scalar) -> &'static str {
    match s {
        Scalar::Int => "int64",
        Scalar::String => "string",
        Scalar::Bool => "bool",
        other => other.name(),
    }
}

fn lower_first(text: &str) -> String {
    super::camel(text)
}

pub(super) fn comment(line: &str, indent: &str) -> String {
    if line.is_empty() {
        format!("{indent}//\n")
    } else {
        format!("{indent}// {line}\n")
    }
}

/// A Go doc comment: the first line starts with the declared name, as `go vet` and godoc
/// expect.
pub(super) fn doc(name: &str, lines: &[String], indent: &str) -> String {
    let mut out = String::new();
    for (i, line) in lines.iter().enumerate() {
        let line = one_line(line);
        if i == 0 {
            out.push_str(&format!("{indent}// {name} {line}\n"));
        } else if !line.is_empty() {
            out.push_str(&format!("{indent}// {line}\n"));
        }
    }
    out
}

/// A Go identifier for a local name: camelCase, with a keyword given a trailing `_`.
pub(super) fn local(snake_name: &str) -> String {
    const KEYWORDS: [&str; 25] = [
        "break",
        "case",
        "chan",
        "const",
        "continue",
        "default",
        "defer",
        "else",
        "fallthrough",
        "for",
        "func",
        "go",
        "goto",
        "if",
        "import",
        "interface",
        "map",
        "package",
        "range",
        "return",
        "select",
        "struct",
        "switch",
        "type",
        "var",
    ];
    let name = super::camel(&super::type_ident(snake_name));
    if KEYWORDS.contains(&name.as_str()) {
        format!("{name}_")
    } else {
        name
    }
}

/// The unexported field of a state struct: the domain name (`kind_` for a column `kind`), as
/// a local name.
fn state_field(field: &Field) -> String {
    let name = local(field.name.trim_end_matches('_'));
    if field.name.ends_with('_') && !name.ends_with('_') {
        format!("{name}_")
    } else {
        name
    }
}

