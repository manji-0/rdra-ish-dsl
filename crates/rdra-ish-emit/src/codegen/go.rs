pub(super) fn print_helpers(domain: &DomainModel, out: &mut String) {
    out.push_str("// ── Helpers ──\n\n");
    out.push_str("func isDigits(s string) bool {\n\tif s == \"\" {\n\t\treturn false\n\t}\n\tfor i := 0; i < len(s); i++ {\n\t\tif s[i] < '0' || s[i] > '9' {\n\t\t\treturn false\n\t\t}\n\t}\n\treturn true\n}\n\n");
    out.push_str("// isDecimalText reports whether s is -?[0-9]+(.[0-9]+)?.\nfunc isDecimalText(s string) bool {\n\tif len(s) > 0 && s[0] == '-' {\n\t\ts = s[1:]\n\t}\n\tfor i := 0; i < len(s); i++ {\n\t\tif s[i] == '.' {\n\t\t\treturn isDigits(s[:i]) && isDigits(s[i+1:])\n\t\t}\n\t}\n\treturn isDigits(s)\n}\n\n");
    out.push_str("// isDateText reports whether s is YYYY-MM-DD.\nfunc isDateText(s string) bool {\n\treturn len(s) == 10 && isDigits(s[0:4]) && s[4] == '-' && isDigits(s[5:7]) && s[7] == '-' && isDigits(s[8:10])\n}\n\n");
    out.push_str("// isDateTimeText reports whether s is YYYY-MM-DDTHH:MM, then :SS and a fraction if given,\n// then Z or an offset ±HH:MM.\nfunc isDateTimeText(s string) bool {\n\tif len(s) < 17 || !isDateText(s[:10]) || s[10] != 'T' || !isDigits(s[11:13]) || s[13] != ':' || !isDigits(s[14:16]) {\n\t\treturn false\n\t}\n\trest := s[16:]\n\tif len(rest) >= 3 && rest[0] == ':' && isDigits(rest[1:3]) {\n\t\trest = rest[3:]\n\t\tif len(rest) > 1 && rest[0] == '.' {\n\t\t\ti := 1\n\t\t\tfor i < len(rest) && rest[i] >= '0' && rest[i] <= '9' {\n\t\t\t\ti++\n\t\t\t}\n\t\t\tif i == 1 {\n\t\t\t\treturn false\n\t\t\t}\n\t\t\trest = rest[i:]\n\t\t}\n\t}\n\tif rest == \"Z\" {\n\t\treturn true\n\t}\n\treturn len(rest) == 6 && (rest[0] == '+' || rest[0] == '-') && isDigits(rest[1:3]) && rest[3] == ':' && isDigits(rest[4:6])\n}\n\n");
    if domain.fns.is_empty() && domain.sums.is_empty() {
        return;
    }
    out.push_str("func ptrTo[T any](v T) *T { return &v }\n\n");
    out.push_str("// copyOf returns a pointer to a copy of *p, or nil: a state shares no value with a row.\nfunc copyOf[T any](p *T) *T {\n\tif p == nil {\n\t\treturn nil\n\t}\n\tv := *p\n\treturn &v\n}\n\n");
    if domain.fns.is_empty() {
        return;
    }
    out.push_str("// anyOf reports whether some row of rows makes p hold.\nfunc anyOf[T any](rows []T, p func(T) bool) bool {\n\tfor _, r := range rows {\n\t\tif p(r) {\n\t\t\treturn true\n\t\t}\n\t}\n\treturn false\n}\n\n");
    out.push_str("// allOf reports whether every row of rows makes p hold.\nfunc allOf[T any](rows []T, p func(T) bool) bool {\n\tfor _, r := range rows {\n\t\tif !p(r) {\n\t\t\treturn false\n\t\t}\n\t}\n\treturn true\n}\n\n");
    out.push_str("// countOf counts the rows of rows that make p hold.\nfunc countOf[T any](rows []T, p func(T) bool) int {\n\tn := 0\n\tfor _, r := range rows {\n\t\tif p(r) {\n\t\t\tn++\n\t\t}\n\t}\n\treturn n\n}\n\n");
}

pub(super) fn print_rows(domain: &DomainModel, out: &mut String) {
    if domain.sums.is_empty() {
        return;
    }
    out.push_str("// ── Rows: the flat shape a store or the wire holds ──\n\n");
    out.push_str(
        "// InvalidRow reports a row whose values no state of its entity holds, by the column.\n",
    );
    out.push_str(&struct_decl(
        "InvalidRow",
        &[
            Line::Cells(vec!["Entity".into(), "string".into()]),
            Line::Cells(vec!["Column".into(), "string".into()]),
            Line::Cells(vec!["Reason".into(), "string".into()]),
        ],
    ));
    out.push_str("// Error names the entity, the column, and the reason.\nfunc (e *InvalidRow) Error() string {\n\treturn e.Entity + \".\" + e.Column + \": \" + e.Reason\n}\n\n");
    for sum in &domain.sums {
        let FieldType::Enum(tag_enum) = &sum.tag.ty else {
            continue;
        };
        out.push_str(&doc(
            &sum.row,
            &[format!(
                "holds every column of {} as the data layer declares it, the tag {} among them.",
                sum.entity, sum.tag.wire
            )],
            "",
        ));
        let mut lines = Vec::new();
        for f in &sum.row_fields {
            field_lines(
                &mut lines,
                &[],
                f.pascal.clone(),
                value_type(&f.ty, f.nullable),
                Some(&f.wire),
            );
        }
        out.push_str(&struct_decl(&sum.row, &lines));
        let invalid = |column: &str, reason: String| {
            format!(
                "&InvalidRow{{Entity: {}, Column: {}, Reason: {}}}",
                string_literal(&sum.entity),
                string_literal(column),
                string_literal(&reason)
            )
        };
        // A tag column marked `@null` holds null in no state: such a row is an InvalidRow, and
        // the row of a state points at its tag.
        let tag_nullable = sum
            .row_fields
            .iter()
            .any(|f| f.wire == sum.tag.wire && f.nullable);
        out.push_str(&format!(
            "// {0}FromRow returns the state row holds, or an *InvalidRow naming the column whose value no\n// state of {0} takes: a tag or a value outside its value set, a text not in its scalar's shape,\n// or a null or a value where the state's rules say otherwise.\nfunc {0}FromRow(row {1}) ({0}, error) {{\n",
            sum.name, sum.row
        ));
        if tag_nullable {
            out.push_str(&format!(
                "\tif row.{} == nil {{\n\t\treturn nil, {}\n\t}}\n\tswitch *row.{} {{\n",
                sum.tag.pascal,
                invalid(&sum.tag.wire, "null, which is no state".to_string()),
                sum.tag.pascal
            ));
        } else {
            out.push_str(&format!("\tswitch row.{} {{\n", sum.tag.pascal));
        }
        for v in &sum.variants {
            out.push_str(&format!("\tcase {tag_enum}{}:\n", v.value.ident));
            for f in &v.always_null {
                out.push_str(&format!(
                    "\t\tif row.{} != nil {{\n\t\t\treturn nil, {}\n\t\t}}\n",
                    f.pascal,
                    invalid(&f.wire, format!("null in the state {}", v.value.wire))
                ));
            }
            let mut inits = Vec::new();
            for f in &v.fields {
                let declared = sum.row_fields.iter().find(|r| r.wire == f.wire);
                let row_nullable = declared.is_some_and(|d| d.nullable);
                if row_nullable && !f.nullable {
                    out.push_str(&format!(
                        "\t\tif row.{} == nil {{\n\t\t\treturn nil, {}\n\t\t}}\n",
                        f.pascal,
                        invalid(&f.wire, format!("present in the state {}", v.value.wire))
                    ));
                    inits.push(format!("{}: *row.{}", state_field(f), f.pascal));
                } else if f.nullable {
                    inits.push(format!("{}: copyOf(row.{})", state_field(f), f.pascal));
                } else {
                    inits.push(format!("{}: row.{}", state_field(f), f.pascal));
                }
                let checked = match &f.ty {
                    FieldType::Enum(e) => Some(e.clone()),
                    FieldType::Scalar(s) if Scalar::PRELUDE.contains(s) => {
                        Some(s.name().to_string())
                    }
                    _ => None,
                };
                if let Some(ty) = checked {
                    let check = if row_nullable && f.nullable {
                        format!("row.{0} != nil && !row.{0}.Valid()", f.pascal)
                    } else {
                        format!("!row.{}.Valid()", f.pascal)
                    };
                    out.push_str(&format!(
                        "\t\tif {check} {{\n\t\t\treturn nil, {}\n\t\t}}\n",
                        invalid(&f.wire, format!("not a value of {ty}"))
                    ));
                }
            }
            out.push_str(&format!(
                "\t\treturn {}{{{}}}, nil\n",
                concrete(domain, &v.name),
                inits.join(", ")
            ));
        }
        out.push_str(&format!(
            "\t}}\n\treturn nil, {}\n}}\n\n",
            invalid(&sum.tag.wire, format!("not a value of {tag_enum}"))
        ));
        out.push_str(&format!(
            "// {0}ToRow returns the flat row of a state; a nil state gives the zero {1}.\nfunc {0}ToRow(state {0}) {1} {{\n\tif state == nil {{\n\t\treturn {1}{{}}\n\t}}\n\treturn state.row()\n}}\n\n",
            sum.name, sum.row
        ));
        for v in &sum.variants {
            let mut inits = Vec::new();
            for f in &sum.row_fields {
                if f.wire == sum.tag.wire && tag_nullable {
                    inits.push(format!("{}: ptrTo({tag_enum}{})", f.pascal, v.value.ident));
                } else if f.wire == sum.tag.wire {
                    inits.push(format!("{}: {tag_enum}{}", f.pascal, v.value.ident));
                } else if v.always_null.iter().any(|n| n.wire == f.wire) {
                    inits.push(format!("{}: nil", f.pascal));
                } else if let Some(vf) = v.fields.iter().find(|x| x.wire == f.wire) {
                    let read = format!("s.{}", state_field(vf));
                    if f.nullable && !vf.nullable {
                        inits.push(format!("{}: ptrTo({read})", f.pascal));
                    } else if f.nullable {
                        inits.push(format!("{}: copyOf({read})", f.pascal));
                    } else {
                        inits.push(format!("{}: {read}", f.pascal));
                    }
                }
            }
            out.push_str(&format!(
                "func (s {}) row() {} {{\n\treturn {}{{{}}}\n}}\n\n",
                concrete(domain, &v.name),
                sum.row,
                sum.row,
                inits.join(", ")
            ));
        }
    }
}

pub(super) fn print_dispatchers(domain: &DomainModel, out: &mut String) {
    if domain.dispatchers.is_empty() {
        return;
    }
    out.push_str("// ── Dispatch: run a use case from whatever states its rows are in ──\n\n");
    for d in &domain.dispatchers {
        let err = error_name(domain, &d.usecase);
        out.push_str(&format!(
            "// {} is what {} returns when the use case runs: one case is set.\n",
            d.outcome, d.name
        ));
        let lines: Vec<Line> = d
            .cases
            .iter()
            .map(|c| Line::Cells(vec![c.case.clone(), format!("*{}", c.result)]))
            .collect();
        out.push_str(&struct_decl(&d.outcome, &lines));
        let mut params: Vec<String> = d
            .rows
            .iter()
            .map(|(n, ty)| format!("{} {ty}", local(n)))
            .collect();
        for (n, ty) in &d.marks {
            params.push(format!("{} {ty}", local(n)));
        }
        for i in &d.inputs {
            params.push(format!(
                "{} {}",
                local(&i.name),
                value_type(&i.ty, i.nullable)
            ));
        }
        for (n, ty) in &d.choices {
            params.push(format!("{} {ty}", local(n)));
        }
        out.push_str(&format!(
            "// {} runs {} from whatever states its rows are in: the transition function of those states.\n// Its error is a *{err}: NotEnabled when no function runs from them, or the function's error.\nfunc {}({}) ({}, error) {{\n",
            d.name,
            d.usecase,
            d.name,
            params.join(", "),
            d.outcome
        ));
        for (n, ty) in &d.rows {
            if is_sum(domain, ty) {
                out.push_str(&format!(
                    "\tif {} == nil {{\n\t\treturn {}{{}}, {}\n\t}}\n",
                    local(n),
                    d.outcome,
                    use_case_error(
                        domain,
                        &d.usecase,
                        "InvalidArgument",
                        &format!(
                            "&InvalidArgument{{Reason: {}}}",
                            string_literal(&format!("{n} is nil: no state"))
                        )
                    )
                ));
            }
        }
        for c in &d.cases {
            let mut depth = 1;
            for (s, (n, _)) in c.states.iter().zip(&d.rows) {
                if let Some((ty, _, _)) = s {
                    out.push_str(&format!(
                        "{}if {1}, ok := {1}.({ty}); ok {{\n",
                        "\t".repeat(depth),
                        local(n)
                    ));
                    depth += 1;
                }
            }
            for (i, v) in &c.choice {
                let (n, ty) = &d.choices[*i];
                out.push_str(&format!(
                    "{}if {} == {ty}{} {{\n",
                    "\t".repeat(depth),
                    local(n),
                    v.ident
                ));
                depth += 1;
            }
            let mut args: Vec<String> = d.rows.iter().map(|(n, _)| local(n)).collect();
            args.extend(d.marks.iter().map(|(n, _)| local(n)));
            args.extend(c.inputs.iter().map(|i| local(&d.inputs[*i].name)));
            let ind = "\t".repeat(depth);
            out.push_str(&format!(
                "{ind}r, err := {}({})\n{ind}if err != nil {{\n{ind}\treturn {}{{}}, err\n{ind}}}\n",
                c.function,
                args.join(", "),
                d.outcome
            ));
            out.push_str(&format!(
                "{ind}return {}{{{}: &r}}, nil\n",
                d.outcome, c.case
            ));
            for k in (1..depth).rev() {
                out.push_str(&format!("{}}}\n", "\t".repeat(k)));
            }
        }
        out.push_str(&format!(
            "\treturn {}{{}}, {}\n}}\n\n",
            d.outcome,
            use_case_error(
                domain,
                &d.usecase,
                "NotEnabled",
                &format!("&NotEnabled{{UseCase: {}}}", string_literal(&d.usecase))
            )
        ));
    }
}
