/// The names the Go printer derives from the IR's (`super::derived_names`): each is claimed
/// after every IR name, and read back with [`derived`], `_` appended on a collision.
pub(super) fn derived_names(domain: &DomainModel) -> Vec<super::DerivedName> {
    let mut out = Vec::new();
    let mut push =
        |key: String, name: String, by: String| out.push(super::DerivedName { key, name, by });
    for sum in &domain.sums {
        push(
            format!("go:visitor:{}", sum.name),
            format!("{}Visitor", sum.name),
            format!("the Go visitor of {}", sum.name),
        );
        push(
            format!("go:match:{}", sum.name),
            format!("Match{}", sum.name),
            format!("the Go match function of {}", sum.name),
        );
        for v in &sum.variants {
            push(
                format!("go:kindconst:{}:{}", sum.name, v.value.ident),
                format!("{}{}", sum.kind, v.value.ident),
                format!("the Go kind constant of {}", v.name),
            );
            push(
                format!("go:state:{}:{}", sum.name, v.value.ident),
                format!("{}State", lower_first(&v.name)),
                format!("the Go struct of the state {}", v.name),
            );
        }
    }
    let mut seen: Vec<&str> = Vec::new();
    for f in &domain.fns {
        if seen.contains(&f.usecase.as_str()) {
            continue;
        }
        seen.push(&f.usecase);
        let name = error_name(domain, &f.usecase);
        push(
            format!("go:errorkind:{}", f.usecase),
            format!("{name}Kind"),
            format!("the Go kind of {name}"),
        );
        for case in error_case_names(domain, &f.usecase) {
            push(
                format!("go:errorcase:{}:{case}", f.usecase),
                format!("{name}{case}"),
                format!("the Go case {case} of {name}"),
            );
        }
    }
    for cap in &domain.capabilities {
        push(
            format!("go:issue:{}", cap.actor),
            format!("Issue{}", cap.name),
            format!("the Go constructor of {}", cap.name),
        );
    }
    if !domain.capabilities.is_empty() {
        push(
            "go:callervalid".to_string(),
            "CallerValid".to_string(),
            "the Go check of a caller".to_string(),
        );
    }
    out
}

/// The name claimed under `key`, else `fallback` (a domain built for no language).
pub(super) fn derived(
    domain: &DomainModel,
    key: &str,
    fallback: impl FnOnce() -> String,
) -> String {
    domain.derived(key).map_or_else(fallback, str::to_string)
}

/// The cases of a use case's error in Go, in order.
fn error_case_names(domain: &DomainModel, usecase: &str) -> Vec<&'static str> {
    let (rejects, invalid) = error_cases(domain, usecase);
    let mut cases = vec!["NotEnabled"];
    if rejects {
        cases.push("Rejected");
    }
    if invalid {
        cases.push("InvalidArgument");
    }
    cases
}

/// The type of a use case error's `Kind`.
fn error_kind(domain: &DomainModel, usecase: &str) -> String {
    derived(domain, &format!("go:errorkind:{usecase}"), || {
        format!("{}Kind", error_name(domain, usecase))
    })
}

/// The constant of a use case error's case.
fn error_case(domain: &DomainModel, usecase: &str, case: &str) -> String {
    derived(domain, &format!("go:errorcase:{usecase}:{case}"), || {
        format!("{}{case}", error_name(domain, usecase))
    })
}

/// The kind constant of the state `v` of `sum`.
fn kind_const(domain: &DomainModel, sum: &SumDecl, v: &VariantDecl) -> String {
    derived(
        domain,
        &format!("go:kindconst:{}:{}", sum.name, v.value.ident),
        || format!("{}{}", sum.kind, v.value.ident),
    )
}

/// The unexported struct that implements the state interface `variant`: the name has no
/// spelling a local name of the printed functions takes.
fn concrete(domain: &DomainModel, variant: &str) -> String {
    for sum in &domain.sums {
        if let Some(v) = sum.variants.iter().find(|v| v.name == variant) {
            return derived(
                domain,
                &format!("go:state:{}:{}", sum.name, v.value.ident),
                || format!("{}State", lower_first(variant)),
            );
        }
    }
    format!("{}State", lower_first(variant))
}

/// The variant `ty` names, when it is the type of a state.
fn variant_of<'d>(domain: &'d DomainModel, ty: &str) -> Option<&'d VariantDecl> {
    domain
        .sums
        .iter()
        .flat_map(|s| s.variants.iter())
        .find(|v| v.name == ty)
}

/// Whether `ty` is the type of a state: an interface, read by its methods.
fn is_variant(domain: &DomainModel, ty: &str) -> bool {
    variant_of(domain, ty).is_some()
}

/// Whether `ty` is a state type (the sum of an entity's states): an interface.
fn is_sum(domain: &DomainModel, ty: &str) -> bool {
    domain.sums.iter().any(|s| s.name == ty)
}

/// How the printed functions read `field` of a value of type `ty`: a state's accessor, or a
/// record's or row's exported field.
fn member(domain: &DomainModel, ty: &str, field: &Field) -> String {
    if is_variant(domain, ty) {
        format!("{}()", field.domain_pascal())
    } else {
        field.pascal.clone()
    }
}

// ── Scalars, ids, value sets ─────────────────────────────────────────────────

/// The shape check of a prelude scalar: the function its parser and `Valid` call.
fn shape_check(s: Scalar) -> &'static str {
    match s {
        Scalar::Date => "isDateText",
        Scalar::DateTime => "isDateTimeText",
        _ => "isDecimalText",
    }
}

/// What a prelude scalar's text must look like, for its doc comment.
fn shape_doc(s: Scalar) -> &'static str {
    match s {
        Scalar::Date => "a date, YYYY-MM-DD",
        Scalar::DateTime => {
            "a date and time, YYYY-MM-DDTHH:MM[:SS[.frac]] then Z or an offset ±HH:MM"
        }
        _ => "decimal text, -?[0-9]+(.[0-9]+)?",
    }
}

fn print_scalars(out: &mut String) {
    out.push_str("// ── Scalars: replace with the project's own types if it has them ──\n\n");
    for s in Scalar::PRELUDE {
        let name = s.name();
        out.push_str(&doc(
            name,
            &[
                format!("is {}", lower_first(s.default_doc())),
                format!(
                    "Parse{name} makes one from text and checks its shape: {}.",
                    shape_doc(s)
                ),
            ],
            "",
        ));
        out.push_str(&format!("type {name} string\n\n"));
        out.push_str(&format!(
            "// Parse{name} returns s as a {name}, or an *InvalidValue when s is not {}.\nfunc Parse{name}(s string) ({name}, error) {{\n\tif !{check}(s) {{\n\t\treturn \"\", &InvalidValue{{Type: {lit}, Value: s}}\n\t}}\n\treturn {name}(s), nil\n}}\n\n",
            shape_doc(s),
            check = shape_check(s),
            lit = string_literal(name),
        ));
        out.push_str(&format!(
            "// Valid reports whether v has the shape Parse{name} takes.\nfunc (v {name}) Valid() bool {{\n\treturn {}(string(v))\n}}\n\n",
            shape_check(s)
        ));
    }
    out.push_str("// InvalidValue reports text that is no value of a type: a value set's, or a scalar's shape.\n");
    out.push_str(&struct_decl(
        "InvalidValue",
        &[
            Line::Cells(vec!["Type".into(), "string".into()]),
            Line::Cells(vec!["Value".into(), "string".into()]),
        ],
    ));
    out.push_str("// Error names the type and the text.\nfunc (e *InvalidValue) Error() string {\n\treturn \"not a value of \" + e.Type + \": \" + e.Value\n}\n\n");
}

fn print_ids(domain: &DomainModel, out: &mut String) {
    if domain.ids.is_empty() {
        return;
    }
    out.push_str("// ── Ids ──\n\n");
    for id in &domain.ids {
        let repr = scalar(id.repr);
        out.push_str(&doc(
            &id.name,
            &[format!(
                "is the id of entity {}. Parse{} makes one.",
                id.entity, id.name
            )],
            "",
        ));
        out.push_str(&format!("type {} {repr}\n\n", id.name));
        if Scalar::PRELUDE.contains(&id.repr) {
            out.push_str(&format!(
                "// Parse{0} returns v as a {0}, or an *InvalidValue when v is not {1}.\nfunc Parse{0}(v string) ({0}, error) {{\n\tif !{2}(v) {{\n\t\treturn \"\", &InvalidValue{{Type: {3}, Value: v}}\n\t}}\n\treturn {0}(v), nil\n}}\n\n",
                id.name,
                shape_doc(id.repr),
                shape_check(id.repr),
                string_literal(&id.name)
            ));
        } else {
            let base = match id.repr {
                Scalar::Int => "int64",
                Scalar::Bool => "bool",
                _ => "string",
            };
            out.push_str(&format!(
                "// Parse{0} returns v as a {0}: every {1} is one, so the error is always nil.\nfunc Parse{0}(v {1}) ({0}, error) {{\n\treturn {0}(v), nil\n}}\n\n",
                id.name, base
            ));
        }
    }
}

fn print_enums(domain: &DomainModel, out: &mut String) {
    if domain.enums.is_empty() {
        return;
    }
    out.push_str("// ── Value sets ──\n\n");
    for decl in &domain.enums {
        let lines = vec![
            format!("is {}", one_line(&decl.doc.join(" "))),
            format!(
                "Its values are the {0}* constants; Parse{0} reads one from text.",
                decl.name
            ),
        ];
        out.push_str(&doc(&decl.name, &lines, ""));
        out.push_str(&format!("type {} string\n\n", decl.name));
        let mut consts = Vec::new();
        for value in &decl.values {
            if let Some(label) = &value.label {
                consts.push(Line::Comment(format!(
                    "{}{} is {}.",
                    decl.name,
                    value.ident,
                    one_line(label)
                )));
            }
            consts.push(Line::Cells(vec![
                format!("{}{}", decl.name, value.ident),
                decl.name.clone(),
                format!("= {}", string_literal(&value.wire)),
            ]));
        }
        out.push_str(&format!(
            "// The values of {}.\nconst (\n{})\n\n",
            decl.name,
            block(&consts)
        ));
        out.push_str(&format!(
            "// {0}Values lists every value of {0} in declaration order.\nvar {0}Values = []{0}{{{1}}}\n\n",
            decl.name,
            decl.values
                .iter()
                .map(|v| format!("{}{}", decl.name, v.ident))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        out.push_str(&format!(
            "// Valid reports whether v is one of the values of {0}.\nfunc (v {0}) Valid() bool {{\n\tfor _, x := range {0}Values {{\n\t\tif v == x {{\n\t\t\treturn true\n\t\t}}\n\t}}\n\treturn false\n}}\n\n",
            decl.name
        ));
        out.push_str(&format!(
            "// Parse{0} returns the value of {0} the model spells s, or an *InvalidValue when there is none.\nfunc Parse{0}(s string) ({0}, error) {{\n\tif v := {0}(s); v.Valid() {{\n\t\treturn v, nil\n\t}}\n\treturn \"\", &InvalidValue{{Type: {1}, Value: s}}\n}}\n\n",
            decl.name,
            string_literal(&decl.name)
        ));
    }
}

fn print_records(domain: &DomainModel, out: &mut String) {
    for kind in [RecordKind::Entity, RecordKind::Dto] {
        let records: Vec<_> = domain.records.iter().filter(|r| r.kind == kind).collect();
        if records.is_empty() {
            continue;
        }
        out.push_str(match kind {
            RecordKind::Entity => "// ── Entities ──\n\n",
            RecordKind::Dto => "// ── DTOs ──\n\n",
        });
        for record in records {
            out.push_str(&doc(
                &record.name,
                &[format!("is {}", one_line(&record.doc.join(" ")))],
                "",
            ));
            let mut lines = Vec::new();
            for field in &record.fields {
                field_lines(
                    &mut lines,
                    &field.doc,
                    field.pascal.clone(),
                    value_type(&field.ty, field.nullable),
                    Some(&field.wire),
                );
            }
            out.push_str(&struct_decl(&record.name, &lines));
        }
    }
}

// ── States ───────────────────────────────────────────────────────────────────

fn print_sum(domain: &DomainModel, sum: &SumDecl, out: &mut String) {
    if std::ptr::eq(sum, &domain.sums[0]) {
        out.push_str("// ── Entities with states ──\n\n");
    }
    let marker = format!("is{}", sum.name);
    let kind = &sum.kind;
    out.push_str(&doc(
        kind,
        &[format!(
            "tells the states of {} apart: one value per state, the value of Kind().",
            sum.name
        )],
        "",
    ));
    out.push_str(&format!("type {kind} string\n\n"));
    let consts: Vec<Line> = sum
        .variants
        .iter()
        .map(|v| {
            Line::Cells(vec![
                kind_const(domain, sum, v),
                kind.clone(),
                format!("= {}", string_literal(&v.value.ident)),
            ])
        })
        .collect();
    out.push_str(&format!(
        "// The kinds of {}.\nconst (\n{})\n\n",
        sum.name,
        block(&consts)
    ));

    let names: Vec<&str> = sum.variants.iter().map(|v| v.name.as_str()).collect();
    out.push_str(&doc(
        &sum.name,
        &[
            format!("is {}", one_line(&sum.doc.join(" "))),
            format!(
                "It is one of {}, told apart by Kind(). Only this package makes a state: in a transition function or {}FromRow.",
                names.join(", "),
                sum.name
            ),
        ],
        "",
    ));
    let rules = if domain.validators.is_empty() {
        ""
    } else {
        "\t// RuleViolations returns the rules the row breaks in its state.\n\tRuleViolations() []string\n"
    };
    out.push_str(&format!(
        "type {} interface {{\n\t// Kind is the state's kind.\n\tKind() {kind}\n{rules}\t{marker}()\n\trow() {}\n}}\n\n",
        sum.name, sum.row
    ));

    for variant in &sum.variants {
        let own = format!("is{}", variant.name);
        let mut lines = vec![format!("is {}", one_line(&variant.doc.join(" ")))];
        for field in &variant.always_null {
            lines.push(format!(
                "{}: {}",
                field.wire,
                field.doc.last().cloned().unwrap_or_default()
            ));
        }
        lines.push(format!(
            "Only this package makes one, in a transition function or {}FromRow; a nil {} is no state.",
            sum.name, variant.name
        ));
        out.push_str(&doc(&variant.name, &lines, ""));
        let mut methods = format!("\t{}\n", sum.name);
        for field in &variant.fields {
            let ty = value_type(&field.ty, field.nullable);
            let doc = if field.nullable {
                format!(
                    "{} returns {}, nil when it is null: a copy, so the state does not change.",
                    field.domain_pascal(),
                    field.wire
                )
            } else {
                format!("{} returns {}.", field.domain_pascal(), field.wire)
            };
            methods.push_str(&format!("\t// {doc}\n\t{}() {ty}\n", field.domain_pascal()));
        }
        methods.push_str(&format!("\t{own}()\n"));
        out.push_str(&format!(
            "type {} interface {{\n{methods}}}\n\n",
            variant.name
        ));

        let st = concrete(domain, &variant.name);
        let mut lines = Vec::new();
        for field in &variant.fields {
            field_lines(
                &mut lines,
                &field.doc,
                state_field(field),
                value_type(&field.ty, field.nullable),
                None,
            );
        }
        out.push_str(&format!(
            "// {st} is the one implementation of {}.\n",
            variant.name
        ));
        out.push_str(&struct_decl(&st, &lines));
        for field in &variant.fields {
            let ty = value_type(&field.ty, field.nullable);
            let read = if field.nullable {
                format!("copyOf(s.{})", state_field(field))
            } else {
                format!("s.{}", state_field(field))
            };
            out.push_str(&format!(
                "func (s {st}) {}() {ty} {{\n\treturn {read}\n}}\n\n",
                field.domain_pascal()
            ));
        }
        out.push_str(&format!(
            "func ({st}) Kind() {kind} {{\n\treturn {}\n}}\n\n",
            kind_const(domain, sum, variant)
        ));
        out.push_str(&format!("func ({st}) {marker}() {{}}\n\n"));
        out.push_str(&format!("func ({st}) {own}() {{}}\n\n"));
    }
    print_visitor(domain, sum, out);
}

/// `<Entity>Visitor`, one method per state, and `Match<Entity>`, which calls the method of a
/// state's own: a state the model gains is a method an implementation lacks, so the code that
/// matches states stops compiling until it handles it (P7 of docs/design/code-check.md).
fn print_visitor(domain: &DomainModel, sum: &SumDecl, out: &mut String) {
    let visitor = derived(domain, &format!("go:visitor:{}", sum.name), || {
        format!("{}Visitor", sum.name)
    });
    let matcher = derived(domain, &format!("go:match:{}", sum.name), || {
        format!("Match{}", sum.name)
    });
    out.push_str(&format!(
        "// {visitor} has one method per state of {0}, which {matcher} calls. When the model gains a\n// state, {visitor} gains its method, and an implementation that lacks it no longer compiles\n// where {matcher} takes it: Go's type switch says nothing of a state it misses.\n",
        sum.name
    ));
    let mut methods = String::new();
    for v in &sum.variants {
        methods.push_str(&format!(
            "\t// {0} is called on a state of kind {1}.\n\t{0}({2}) R\n",
            v.value.ident,
            kind_const(domain, sum, v),
            v.name
        ));
    }
    out.push_str(&format!(
        "type {visitor}[R any] interface {{\n{methods}}}\n\n"
    ));
    out.push_str(&format!(
        "// {matcher} calls the method of v for the state of state and returns what it returns. A nil\n// state, or a value of another type that embeds a state, is an *InvalidArgument.\nfunc {matcher}[R any](state {0}, v {visitor}[R]) (R, error) {{\n\tswitch s := state.(type) {{\n",
        sum.name
    ));
    for v in &sum.variants {
        out.push_str(&format!(
            "\tcase {}:\n\t\treturn v.{}(s), nil\n",
            concrete(domain, &v.name),
            v.value.ident
        ));
    }
    out.push_str(&format!(
        "\t}}\n\tvar zero R\n\treturn zero, &InvalidArgument{{Reason: {}}}\n}}\n\n",
        string_literal(&format!("no state of {} this package made", sum.name))
    ));
}

// ── Use cases ────────────────────────────────────────────────────────────────

/// The cases of a use case's error in Go: NotEnabled always; Rejected when a condition applies;
/// InvalidArgument when the IR says so, or when an argument can be what Go lets a caller build
/// and the model never holds: a nil state, a text that is no value of its value set or scalar.
fn error_cases(domain: &DomainModel, usecase: &str) -> (bool, bool) {
    let decl = domain.error_of(usecase);
    let rejects = decl.is_some_and(|d| d.rejects);
    let invalid = decl.is_some_and(|d| d.invalid_argument)
        || domain
            .fns
            .iter()
            .filter(|f| f.usecase == usecase)
            .any(|f| go_invalid(domain, f));
    (rejects, invalid)
}

/// Whether Go lets a caller pass `f` an argument the model never holds.
fn go_invalid(domain: &DomainModel, f: &FnDecl) -> bool {
    f.rows.iter().any(|r| is_variant(domain, &r.ty))
        || f.inputs.iter().any(|i| checked_input(&i.ty))
}

/// Whether an input of type `ty` is checked: a value set's or a prelude scalar's text.
fn checked_input(ty: &FieldType) -> bool {
    matches!(ty, FieldType::Enum(_))
        || matches!(ty, FieldType::Scalar(s) if Scalar::PRELUDE.contains(s))
}

/// The error type of `usecase`.
fn error_name(domain: &DomainModel, usecase: &str) -> String {
    domain
        .error_of(usecase)
        .map(|e| e.name.clone())
        .unwrap_or_else(|| format!("{}Error", super::type_ident(usecase)))
}

/// `&<UseCase>Error{Kind: .., Err: detail}`.
fn use_case_error(domain: &DomainModel, usecase: &str, case: &str, detail: &str) -> String {
    format!(
        "&{}{{Kind: {}, Err: {detail}}}",
        error_name(domain, usecase),
        error_case(domain, usecase, case)
    )
}

/// The detail types every `<UseCase>Error` shares, and `Match<Entity>` returns.
fn print_error_details(out: &mut String) {
    out.push_str("// ── Errors ──\n\n");
    let detail = |out: &mut String,
                  name: &str,
                  sentinel: &str,
                  doc: &str,
                  fields: &[(&str, &str)],
                  message: &str| {
        out.push_str(&format!(
            "// Err{name} is what errors.Is matches a *{name} with.\nvar Err{name} = errors.New({})\n\n",
            string_literal(sentinel)
        ));
        out.push_str(&format!("// {name} {doc}\n"));
        let lines: Vec<Line> = fields
            .iter()
            .map(|(f, t)| Line::Cells(vec![f.to_string(), t.to_string()]))
            .collect();
        out.push_str(&struct_decl(name, &lines));
        out.push_str(&format!(
            "// Error says what happened.\nfunc (e *{name}) Error() string {{\n\treturn {message}\n}}\n\n"
        ));
        out.push_str(&format!(
            "// Is reports whether target is Err{name}.\nfunc (e *{name}) Is(target error) bool {{\n\treturn target == Err{name}\n}}\n\n"
        ));
    };
    detail(
        out,
        "NotEnabled",
        "the use case does not run from these states",
        "reports rows in states the use case does not run from, or a commit that found a row it writes changed since the read.",
        &[("UseCase", "string")],
        "\"the use case \" + e.UseCase + \" does not run from these states\"",
    );
    detail(
        out,
        "Rejected",
        "rejected by a condition",
        "reports a condition of a use case that did not hold: the use case does not run.",
        &[
            ("Condition", "string"),
            ("Label", "string"),
            ("Site", "string"),
        ],
        "\"rejected by the condition \" + e.Condition + \": \" + e.Label",
    );
    detail(
        out,
        "InvalidArgument",
        "an argument the verified model never holds",
        "reports arguments that break what the verified model keeps: a nil state or one this package did not make, a text that is no value of its type, a row that does not name the row passed with it, a column the state keeps null that holds a value.",
        &[("Reason", "string")],
        "\"invalid argument: \" + e.Reason",
    );
}

fn print_errors(domain: &DomainModel, out: &mut String) {
    out.push_str("// ── Use cases ──\n\n");
    out.push_str("// ExpectedSource is what a row a result writes must still be when the write commits, so the\n// store can write it conditionally and take a write that matches no row as NotEnabled (see the\n// obligations). Absent: the row is created, and no row has its id. Otherwise the row exists,\n// and when Column is set, it holds Value.\n");
    out.push_str(&struct_decl(
        "ExpectedSource",
        &[
            Line::Cells(vec!["Absent".into(), "bool".into()]),
            Line::Cells(vec!["Column".into(), "string".into()]),
            Line::Cells(vec!["Value".into(), "string".into()]),
        ],
    ));
    let mut seen: Vec<&str> = Vec::new();
    for f in &domain.fns {
        if seen.contains(&f.usecase.as_str()) {
            continue;
        }
        seen.push(&f.usecase);
        let name = error_name(domain, &f.usecase);
        let kind = error_kind(domain, &f.usecase);
        let cases: Vec<(&str, String)> = error_case_names(domain, &f.usecase)
            .into_iter()
            .map(|case| {
                let why = match case {
                    "NotEnabled" => format!(
                        "the rows are in states {} does not run from (only its dispatcher says so), or a store's commit found a row changed.",
                        f.usecase
                    ),
                    "Rejected" => "a condition applied to the use case does not hold.".to_string(),
                    _ => "the arguments break what the verified model keeps.".to_string(),
                };
                (case, why)
            })
            .collect();
        out.push_str(&format!(
            "// {kind} is the case of a {name}.\ntype {kind} string\n\n"
        ));
        let mut consts = Vec::new();
        for (case, why) in &cases {
            let constant = error_case(domain, &f.usecase, case);
            consts.push(Line::Comment(format!("{constant}: {why}")));
            consts.push(Line::Cells(vec![
                constant,
                kind.clone(),
                format!("= {}", string_literal(case)),
            ]));
        }
        out.push_str(&format!(
            "// The cases of {name}.\nconst (\n{})\n\n",
            block(&consts)
        ));
        let details: Vec<String> = cases.iter().map(|(c, _)| format!("*{c}")).collect();
        out.push_str(&format!(
            "// {name} is why {0} did not run. Kind is its case, and Err the case's detail ({1}), which errors.As reaches and errors.Is matches with Err{2}.\n",
            f.usecase,
            details.join(", "),
            cases.iter().map(|(c, _)| *c).collect::<Vec<_>>().join(", Err"),
        ));
        out.push_str(&struct_decl(
            &name,
            &[
                Line::Cells(vec!["Kind".into(), kind.clone()]),
                Line::Cells(vec!["Err".into(), "error".into()]),
            ],
        ));
        out.push_str(&format!(
            "// Error names the use case and the case.\nfunc (e *{name}) Error() string {{\n\tif e.Err == nil {{\n\t\treturn {0} + string(e.Kind)\n\t}}\n\treturn {0} + e.Err.Error()\n}}\n\n",
            string_literal(&format!("{}: ", f.usecase))
        ));
        out.push_str(&format!(
            "// Unwrap returns the case's detail.\nfunc (e *{name}) Unwrap() error {{\n\treturn e.Err\n}}\n\n"
        ));
    }
}

pub(super) fn print_functions(domain: &DomainModel, out: &mut String) {
    use super::ir::{Adapt, ArgCheck, Assigned, OutKind};
    if !domain.events.is_empty() {
        out.push_str("// ── Events ──\n\n");
    }
    for event in &domain.events {
        out.push_str(&doc(
            &event.name,
            &[format!("is the event {}.", one_line(&event.doc.join(" ")))],
            "",
        ));
        let mut lines = Vec::new();
        for field in &event.fields {
            let name = super::type_ident(&field.name);
            lines.push(Line::Comment(format!(
                "{name} is the {} row the event was raised on.",
                field.entity
            )));
            lines.push(Line::Cells(vec![name, field.id_ty.clone()]));
        }
        out.push_str(&struct_decl(&event.name, &lines));
    }
    if domain.fns.is_empty() {
        return;
    }
    if !domain.marks.is_empty() {
        out.push_str("// ── Run marks of use cases split into transactions ──\n\n");
    }
    for m in &domain.marks {
        out.push_str(&format!(
            "// {} is the mark step {} of {} leaves on a {} row: the next step takes it. Store it with the row.\n",
            m.name, m.step, m.usecase, m.entity
        ));
        out.push_str(&struct_decl(
            &m.name,
            &[Line::Cells(vec!["Id".into(), m.id_ty.clone()])],
        ));
    }
    print_errors(domain, out);
    for f in &domain.fns {
        let err = error_name(domain, &f.usecase);
        let fail = |case: &str, detail: String, ind: &str| {
            format!(
                "{ind}\treturn {}{{}}, {}\n",
                f.result,
                use_case_error(domain, &f.usecase, case, &detail)
            )
        };
        let invalid = |reason: &str, ind: &str| {
            fail(
                "InvalidArgument",
                format!("&InvalidArgument{{Reason: {}}}", string_literal(reason)),
                ind,
            )
        };

        out.push_str(&format!("// {} is what {} returns.\n", f.result, f.name));
        let mut lines = Vec::new();
        for o in &f.outputs {
            match &o.kind {
                OutKind::Row { ty, .. } => {
                    lines.push(Line::Cells(vec![super::type_ident(&o.name), ty.clone()]))
                }
                OutKind::Deleted {
                    id: Some((ty, _)), ..
                } => lines.push(Line::Cells(vec![super::type_ident(&o.name), ty.clone()])),
                OutKind::Deleted { id: None, .. } => {}
            }
        }
        for o in &f.outputs {
            lines.push(Line::Cells(vec![
                super::type_ident(&format!("{}_expected", o.name)),
                "ExpectedSource".into(),
            ]));
        }
        for m in &f.marks_out {
            lines.push(Line::Cells(vec![super::type_ident(&m.name), m.ty.clone()]));
        }
        for event in &f.raises {
            lines.push(Line::Cells(vec![event.ty.clone(), event.ty.clone()]));
        }
        out.push_str(&struct_decl(&f.result, &lines));

        let (rejects, _) = error_cases(domain, &f.usecase);
        let mut doc_lines = vec![format!("runs {}", one_line(&f.doc.join(" ")))];
        for c in &f.conditions {
            doc_lines.push(format!(
                "Requires the condition {} ({}){}.",
                c.id,
                one_line(&c.label),
                c.site
                    .as_ref()
                    .map(|s| format!(" at {s}"))
                    .unwrap_or_default()
            ));
        }
        let mut errs = Vec::new();
        if go_invalid(domain, f) || domain.invalid_argument_possible(f) {
            errs.push("InvalidArgument when its arguments break what the verified model keeps");
        }
        if rejects && !f.conditions.is_empty() {
            errs.push("Rejected when a condition does not hold");
        }
        if errs.is_empty() {
            doc_lines.push(
                "It returns new values and changes none of its arguments; its error is always nil."
                    .to_string(),
            );
        } else {
            doc_lines.push(format!(
                "It returns new values and changes none of its arguments; its error is a *{err}: {}.",
                errs.join(", ")
            ));
        }
        out.push_str(&doc(&f.name, &doc_lines, ""));

        let row = |r: usize| local(&f.row(r).name);
        let acc =
            |r: usize, field: &Field| format!("{}.{}", row(r), member(domain, &f.row(r).ty, field));
        let row_ty = |r: usize| f.row(r).ty.clone();
        let input = |i: usize| local(&f.inputs[i].name);
        let mut params: Vec<String> = f
            .rows
            .iter()
            .map(|r| format!("{} {}", local(&r.name), r.ty))
            .collect();
        for m in &f.marks_in {
            params.push(format!("{} {}", local(&m.name), m.ty));
        }
        if let Some(ev) = &f.event_in {
            params.push(format!("{} {}", local(&ev.name), ev.ty));
        }
        for i in &f.inputs {
            params.push(format!(
                "{} {}",
                local(&i.name),
                value_type(&i.ty, i.nullable)
            ));
        }
        out.push_str(&format!(
            "func {}({}) ({}, error) {{\n",
            f.name,
            params.join(", "),
            f.result
        ));
        for r in &f.rows {
            if is_variant(domain, &r.ty) {
                out.push_str(&format!(
                    "\tif _, ok := {}.({}); !ok {{\n{}\t}}\n",
                    local(&r.name),
                    concrete(domain, &r.ty),
                    invalid(
                        &format!("{} is no {} this package made", r.name, r.ty),
                        "\t"
                    )
                ));
            }
        }
        for i in &f.inputs {
            if checked_input(&i.ty) {
                let check = if i.nullable {
                    format!("{0} != nil && !{0}.Valid()", local(&i.name))
                } else {
                    format!("!{}.Valid()", local(&i.name))
                };
                out.push_str(&format!(
                    "\tif {check} {{\n{}\t}}\n",
                    invalid(
                        &format!("{} is not a value of {}", i.name, field_type(&i.ty)),
                        "\t"
                    )
                ));
            }
        }
        for check in &f.checks {
            let (cond, message) = match check {
                ArgCheck::Link {
                    child,
                    child_field,
                    parent,
                    parent_field,
                    message,
                } => {
                    let (c, p) = (acc(*child, child_field), acc(*parent, parent_field));
                    let differs = if child_field.nullable {
                        format!("{c} == nil || *{c} != {p}")
                    } else {
                        format!("{c} != {p}")
                    };
                    (differs, message)
                }
                ArgCheck::EventRow {
                    row: r,
                    field,
                    event_field,
                    message,
                } => {
                    let ev = f
                        .event_in
                        .as_ref()
                        .map(|e| local(&e.name))
                        .unwrap_or_default();
                    (
                        format!(
                            "{} != {ev}.{}",
                            acc(*r, field),
                            super::type_ident(event_field)
                        ),
                        message,
                    )
                }
                ArgCheck::MarkRow {
                    row: r,
                    field,
                    mark,
                    message,
                } => (
                    format!(
                        "{} != {}.Id",
                        acc(*r, field),
                        local(&f.marks_in[*mark].name)
                    ),
                    message,
                ),
                ArgCheck::MustBeNull {
                    row: r,
                    field,
                    message,
                } => (format!("{} != nil", acc(*r, field)), message),
            };
            out.push_str(&format!("\tif {cond} {{\n{}\t}}\n", invalid(message, "\t")));
        }
        for c in &f.conditions {
            out.push_str(&format!(
                "\tif !({}) {{\n{}\t}}\n",
                expr(&c.expr, &row, &row_ty, &acc, &input, 1),
                fail(
                    "Rejected",
                    format!(
                        "&Rejected{{Condition: {}, Label: {}, Site: {}}}",
                        string_literal(&c.id),
                        string_literal(&c.label),
                        string_literal(c.site.as_deref().unwrap_or(""))
                    ),
                    "\t"
                )
            ));
        }
        // Values read before the result: a nullable column the model keeps present, and a
        // second lifecycle column's next value.
        let mut temps = 0usize;
        let mut parts = Vec::new();
        for o in &f.outputs {
            match &o.kind {
                OutKind::Row { ty, fields, .. } => {
                    let mut inits = Vec::new();
                    for (target, assigned) in fields {
                        let wrap = |v: String, w: bool| if w { format!("ptrTo({v})") } else { v };
                        let v = match assigned {
                            Assigned::From {
                                row: r,
                                field,
                                adapt,
                            } => {
                                let read = acc(*r, field);
                                match adapt {
                                    Adapt::Same => read,
                                    Adapt::Wrap => format!("ptrTo({read})"),
                                    Adapt::Unwrap(message) => {
                                        let t = format!("v_{temps}");
                                        temps += 1;
                                        out.push_str(&format!(
                                            "\t{t} := {read}\n\tif {t} == nil {{\n{}\t}}\n",
                                            invalid(message, "\t")
                                        ));
                                        format!("*{t}")
                                    }
                                    Adapt::AbsentNull => "nil".to_string(),
                                }
                            }
                            Assigned::Lit { lit, wrap: w } => wrap(lit_go(lit, &target.ty), *w),
                            Assigned::Input { input: i, wrap: w } => wrap(input(*i), *w),
                            Assigned::ParentId {
                                row: r,
                                field,
                                wrap: w,
                            } => wrap(acc(*r, field), *w),
                            Assigned::MarkId { mark, wrap: w } => {
                                wrap(format!("{}.Id", local(&f.marks_in[*mark].name)), *w)
                            }
                            Assigned::Switch {
                                row: r,
                                field,
                                enum_ty,
                                arms,
                            } => {
                                let t = format!("v_{temps}");
                                temps += 1;
                                out.push_str(&format!(
                                    "\tvar {t} {enum_ty}\n\tswitch {} {{\n",
                                    acc(*r, field)
                                ));
                                for (from, to) in arms {
                                    out.push_str(&format!(
                                        "\tcase {enum_ty}{}:\n\t\t{t} = {enum_ty}{}\n",
                                        from.ident, to.ident
                                    ));
                                }
                                out.push_str(&format!(
                                    "\tdefault:\n{}\t}}\n",
                                    invalid(
                                        &format!(
                                            "{} is in no state {} moves it from",
                                            field.wire, f.usecase
                                        ),
                                        "\t"
                                    )
                                ));
                                t
                            }
                            Assigned::EventId { field, wrap: w, .. } => wrap(
                                format!(
                                    "{}.{}",
                                    f.event_in
                                        .as_ref()
                                        .map(|e| local(&e.name))
                                        .unwrap_or_default(),
                                    super::type_ident(field)
                                ),
                                *w,
                            ),
                            Assigned::Null => "nil".to_string(),
                            Assigned::Derived { expr: e, wrap: w } => {
                                wrap(expr(e, &row, &row_ty, &acc, &input, 3), *w)
                            }
                        };
                        let key = if is_variant(domain, ty) {
                            state_field(target)
                        } else {
                            target.pascal.clone()
                        };
                        inits.push(format!("{key}: {v}"));
                    }
                    let built = if is_variant(domain, ty) {
                        concrete(domain, ty)
                    } else {
                        ty.clone()
                    };
                    parts.push(format!(
                        "{}: {built}{{{}}}",
                        super::type_ident(&o.name),
                        inits.join(", ")
                    ));
                }
                OutKind::Deleted {
                    row: r,
                    id: Some((_, field)),
                } => parts.push(format!(
                    "{}: {}",
                    super::type_ident(&o.name),
                    acc(*r, field)
                )),
                OutKind::Deleted { id: None, .. } => {}
            }
        }
        for o in &f.outputs {
            let expected = match f.expected(o) {
                super::ir::Expected::Absent => "ExpectedSource{Absent: true}".to_string(),
                super::ir::Expected::Present => "ExpectedSource{}".to_string(),
                super::ir::Expected::In { column, value } => format!(
                    "ExpectedSource{{Column: {}, Value: {}}}",
                    string_literal(&column),
                    string_literal(&value)
                ),
            };
            parts.push(format!(
                "{}: {expected}",
                super::type_ident(&format!("{}_expected", o.name))
            ));
        }
        let source = |s: &super::ir::MarkSource| match s {
            super::ir::MarkSource::Row { row: r, field } => acc(*r, field),
            super::ir::MarkSource::Input(i) => input(*i),
            super::ir::MarkSource::Mark(k) => format!("{}.Id", local(&f.marks_in[*k].name)),
        };
        for m in &f.marks_out {
            parts.push(format!(
                "{}: {}{{Id: {}}}",
                super::type_ident(&m.name),
                m.ty,
                source(&m.source)
            ));
        }
        for event in &f.raises {
            let ids: Vec<String> = event
                .ids
                .iter()
                .map(|(field, s)| format!("{}: {}", super::type_ident(&field.name), source(s)))
                .collect();
            parts.push(format!("{0}: {0}{{{1}}}", event.ty, ids.join(", ")));
        }
        out.push_str(&format!(
            "\treturn {}{{{}}}, nil\n}}\n\n",
            f.result,
            parts.join(", ")
        ));
    }
}

fn lit_go(lit: &super::ir::Lit, ty: &FieldType) -> String {
    match lit {
        super::ir::Lit::Enum { ty, value } => format!("{ty}{}", value.ident),
        super::ir::Lit::Bool(b) => b.to_string(),
        super::ir::Lit::Int(n) => match ty {
            FieldType::Scalar(Scalar::Int) => format!("int64({n})"),
            _ => n.to_string(),
        },
    }
}

/// An expression of a statement at `ind` tabs: a quantifier is a helper call whose predicate
/// is a function literal over lines of its own, as `gofmt` keeps it.
fn expr(
    e: &super::ir::Expr,
    row: &dyn Fn(usize) -> String,
    row_ty: &dyn Fn(usize) -> String,
    acc: &dyn Fn(usize, &Field) -> String,
    input: &dyn Fn(usize) -> String,
    ind: usize,
) -> String {
    use super::ir::Expr;
    let sub = |x: &Expr| expr(x, row, row_ty, acc, input, ind);
    let quantified = |helper: &str, i: usize, elem: usize, body: &Expr| {
        format!(
            "{helper}({}, func({} {}) bool {{\n{}return {}\n{}}})",
            input(i),
            row(elem),
            row_ty(elem),
            "\t".repeat(ind + 1),
            expr(body, row, row_ty, acc, input, ind + 1),
            "\t".repeat(ind)
        )
    };
    match e {
        Expr::True => "true".to_string(),
        Expr::False => "false".to_string(),
        Expr::Not(inner) => format!("!({})", sub(inner)),
        Expr::And(items) if items.is_empty() => "true".to_string(),
        Expr::Or(items) if items.is_empty() => "false".to_string(),
        Expr::And(items) => items
            .iter()
            .map(|i| format!("({})", sub(i)))
            .collect::<Vec<_>>()
            .join(" && "),
        Expr::Or(items) => items
            .iter()
            .map(|i| format!("({})", sub(i)))
            .collect::<Vec<_>>()
            .join(" || "),
        Expr::IsNull { row: r, field } => format!("{} == nil", acc(*r, field)),
        Expr::EnumEq {
            row: r,
            field,
            enum_ty,
            value,
        } if field.nullable => {
            let a = acc(*r, field);
            format!("{a} != nil && *{a} == {enum_ty}{}", value.ident)
        }
        Expr::EnumEq {
            row: r,
            field,
            enum_ty,
            value,
        } => format!("{} == {enum_ty}{}", acc(*r, field), value.ident),
        // Null satisfies no comparison (#359): a nil field equals no value.
        Expr::BoolEq {
            row: r,
            field,
            value,
        } if field.nullable => {
            let a = acc(*r, field);
            format!("{a} != nil && *{a} == {value}")
        }
        Expr::BoolEq {
            row: r,
            field,
            value,
        } => format!("{} == {value}", acc(*r, field)),
        Expr::IntCmp {
            row: r,
            field,
            op,
            value,
        } => format!("{} {} {value}", acc(*r, field), op.symbol()),
        Expr::InputIsNull { input: i } => format!("{} == nil", input(*i)),
        Expr::InputEnumEq {
            input: i,
            nullable,
            enum_ty,
            value,
        } => {
            let x = input(*i);
            if *nullable {
                format!("{x} != nil && *{x} == {enum_ty}{}", value.ident)
            } else {
                format!("{x} == {enum_ty}{}", value.ident)
            }
        }
        Expr::InputBoolEq {
            input: i,
            nullable,
            value,
        } => {
            let x = input(*i);
            if *nullable {
                format!("{x} != nil && *{x} == {value}")
            } else {
                format!("{x} == {value}")
            }
        }
        Expr::KeyEq {
            child,
            child_field,
            parent,
            parent_field,
        } => {
            let c = acc(*child, child_field);
            let p = acc(*parent, parent_field);
            if child_field.nullable {
                format!("{c} != nil && *{c} == {p}")
            } else {
                format!("{c} == {p}")
            }
        }
        Expr::Exists {
            input: i,
            elem,
            body,
        } => quantified("anyOf", *i, *elem, body),
        Expr::Forall {
            input: i,
            elem,
            body,
        } => quantified("allOf", *i, *elem, body),
        Expr::Count {
            input: i,
            elem,
            body,
            op,
            n,
        } => format!(
            "{} {} {n}",
            quantified("countOf", *i, *elem, body),
            op.symbol()
        ),
    }
}

// ── Rule checks ──────────────────────────────────────────────────────────────

pub(super) fn print_validators(domain: &DomainModel, out: &mut String) {
    if domain.validators.is_empty() {
        return;
    }
    out.push_str("// ── Rule checks ──\n\n");
    let row = |_: usize| "row".to_string();
    for v in &domain.validators {
        let state = is_variant(domain, &v.ty);
        let acc = |_: usize, field: &Field| {
            if state {
                format!("row.{}", state_field(field))
            } else {
                format!("row.{}", field.pascal)
            }
        };
        let receiver = if state {
            concrete(domain, &v.ty)
        } else {
            v.ty.clone()
        };
        out.push_str(
            "// RuleViolations returns the rules row breaks, by the names `check` reports: empty when it keeps them all.\n",
        );
        out.push_str(&format!(
            "func (row {receiver}) RuleViolations() []string {{\n\tvar out []string\n"
        ));
        for rule in &v.rules {
            out.push_str(&format!(
                "\t// {}\n\tif {} {{\n\t\tout = append(out, {})\n\t}}\n",
                one_line(&rule.text),
                expr(
                    &fails(&rule.expr),
                    &row,
                    &|_| v.ty.clone(),
                    &acc,
                    &|_| String::new(),
                    1
                ),
                string_literal(&rule.name)
            ));
        }
        out.push_str("\treturn out\n}\n\n");
    }
}

/// The condition under which `e` fails, folded so that a negated comparison reads plainly.
fn fails(e: &super::ir::Expr) -> super::ir::Expr {
    super::actions::simplify(super::ir::Expr::Not(Box::new(e.clone())))
}

