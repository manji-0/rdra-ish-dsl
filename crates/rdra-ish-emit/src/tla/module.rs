//! The module text: header, variables, TypeOK, Init, one operator per action, Next, Spec,
//! and one operator per invariant, after-assert, and property.

use std::collections::{BTreeMap, BTreeSet};

use rdra_ish_core::lifecycle::{
    ActId, Action, Birth, Effect, EntId, Ltl, ParamRole, Pred, Rhs, Start, TransitionSystem, Value,
    VarId, VarKind,
};

use super::pred::Ctx;
use super::{domain_set, needs_fairness, render_value, TlaNames};

pub(super) fn render(ts: &TransitionSystem, names: &TlaNames, module_name: &str) -> String {
    let mut out = format!(
        "---- MODULE {module_name} ----\n\
         \\* Generated by rdra-ish. Do not edit manually.\n\
         \\* Bounds: InstanceCount={} IntRange=0..{}; a verify OK says nothing outside them.\n\n\
         EXTENDS Integers\n\n\
         InstanceCount == {}\n\
         IntRange == 0..{}\n",
        ts.bounds.instances, ts.bounds.int_max, ts.bounds.instances, ts.bounds.int_max
    );
    for e in ts.entity_ids() {
        out.push_str(&format!("{} == 1..InstanceCount\n", names.ids(e)));
    }
    out.push('\n');
    if ts
        .actions()
        .iter()
        .any(|a| a.params.iter().any(|p| p.role == ParamRole::New))
    {
        out.push_str(
            "\\* The lowest absent slot: a create takes it, and a deleted slot is never reused.\n\
             FirstAbsent(ex, i) == ex[i] = \"absent\" /\\ \\A j \\in DOMAIN ex : j < i => ex[j] # \"absent\"\n\n",
        );
    }
    if ts.vars().is_empty() {
        out.push_str(
            "\\* The model has no entities.\n\
             VARIABLE nothing\n\
             vars == <<nothing>>\n\
             TypeOK == TRUE\n\
             Init == nothing = 0\n\
             Next == UNCHANGED vars\n\
             Spec == Init /\\ [][Next]_vars\n\
             ====\n",
        );
        return out;
    }
    let all: Vec<&str> = names.vars().iter().map(String::as_str).collect();
    out.push_str(&format!("VARIABLES {}\n\n", all.join(", ")));
    out.push_str(&format!("vars == <<{}>>\n\n", all.join(", ")));
    type_ok(ts, names, &mut out);
    init(ts, names, &mut out);
    for a in ts.action_ids() {
        action(ts, names, a, &mut out);
    }
    next(ts, names, &mut out);
    checks(ts, names, &mut out);
    out.push_str("====\n");
    out
}

/// The entity whose slots index a per-instance var.
fn owner_entity(kind: &VarKind) -> Option<EntId> {
    match kind {
        VarKind::Exists(e)
        | VarKind::Column { entity: e, .. }
        | VarKind::Prop { entity: e, .. } => Some(*e),
        VarKind::Owner { child, .. } => Some(*child),
        VarKind::Now => None,
    }
}

fn type_ok(ts: &TransitionSystem, names: &TlaNames, out: &mut String) {
    out.push_str("TypeOK ==\n");
    for v in ts.var_ids() {
        let d = ts.var(v);
        let set = domain_set(ts, names, &d.domain);
        match owner_entity(&d.kind) {
            Some(e) => out.push_str(&format!(
                "  /\\ {} \\in [{} -> {set}]\n",
                names.var(v),
                names.ids(e)
            )),
            None => out.push_str(&format!("  /\\ {} \\in {set}\n", names.var(v))),
        }
    }
    out.push('\n');
}

fn init(ts: &TransitionSystem, names: &TlaNames, out: &mut String) {
    out.push_str("Init ==\n");
    for v in ts.var_ids() {
        let d = ts.var(v);
        let name = names.var(v);
        let Some(e) = owner_entity(&d.kind) else {
            out.push_str(&format!(
                "  /\\ {name} = {}\n",
                render_value(&d.domain, d.base)
            ));
            continue;
        };
        let pre = ts.entity(e).birth == Birth::PreExisting;
        let ids = names.ids(e);
        let value = if pre && matches!(d.kind, VarKind::Exists(_)) {
            Value::PRESENT
        } else {
            d.base
        };
        if pre && d.start == Start::Any && ts.entity(e).columns.contains(&v) {
            let set = domain_set(ts, names, &d.domain);
            out.push_str(&format!("  /\\ {name} \\in [{ids} -> {set}]\n"));
        } else {
            out.push_str(&format!(
                "  /\\ {name} = [i \\in {ids} |-> {}]\n",
                render_value(&d.domain, value)
            ));
        }
    }
    out.push('\n');
}

fn signature(names: &TlaNames, id: ActId, a: &Action) -> String {
    if a.params.is_empty() {
        return names.action(id).to_string();
    }
    let ps: Vec<String> = (0..a.params.len()).map(|p| format!("p{p}")).collect();
    format!("{}({})", names.action(id), ps.join(", "))
}

/// `\E p0 \in A_Ids, p1 \in B_Ids : `, or nothing for an action without params.
fn binder(names: &TlaNames, a: &Action, quantifier: &str) -> String {
    if a.params.is_empty() {
        return String::new();
    }
    let ps: Vec<String> = a
        .params
        .iter()
        .enumerate()
        .map(|(p, param)| format!("p{p} \\in {}", names.ids(param.entity)))
        .collect();
    format!("{quantifier} {} : ", ps.join(", "))
}

fn action(ts: &TransitionSystem, names: &TlaNames, id: ActId, out: &mut String) {
    let a = &ts.actions()[id.index()];
    let mut conj: Vec<String> = Vec::new();
    for (p, param) in a.params.iter().enumerate() {
        let exists = names.var(ts.entity(param.entity).exists);
        conj.push(match param.role {
            ParamRole::New => format!("FirstAbsent({exists}, p{p})"),
            ParamRole::Existing | ParamRole::Parent => format!("{exists}[p{p}] = \"present\""),
        });
    }
    for g in &a.guards {
        let mut ctx = Ctx {
            ts,
            names,
            primed: false,
            depth: 0,
        };
        conj.push(ctx.pred(&g.pred));
    }
    let (assigns, written) = effects(ts, names, a);
    conj.extend(assigns);
    let unchanged: Vec<&str> = ts
        .var_ids()
        .filter(|v| !written.contains(v))
        .map(|v| names.var(v))
        .collect();
    match unchanged.as_slice() {
        [] => {}
        [one] => conj.push(format!("UNCHANGED {one}")),
        many => conj.push(format!("UNCHANGED <<{}>>", many.join(", "))),
    }
    out.push_str(&format!("{} ==\n", signature(names, id, a)));
    for c in conj {
        out.push_str(&format!("  /\\ {c}\n"));
    }
    out.push('\n');
}

/// The post-value of one slot, folded over the effects in order.
enum Post {
    Expr(String),
    /// One successor per value (applied after every other effect).
    Choose(Vec<Value>),
}

/// One `v' = [v EXCEPT ..]` per written var, with the explorer's order of application:
/// assignments and transitions in order (last wins), then choices, and a delete resets the
/// deleted slot last.
fn effects(ts: &TransitionSystem, names: &TlaNames, a: &Action) -> (Vec<String>, BTreeSet<VarId>) {
    let mut post: BTreeMap<VarId, BTreeMap<u8, Post>> = BTreeMap::new();
    let mut deleted: Vec<u8> = Vec::new();
    let mut tick = false;
    for eff in &a.effects {
        let (var, param, value) = match eff {
            Effect::Create { param } => {
                let exists = ts.entity(a.params[usize::from(*param)].entity).exists;
                let d = &ts.var(exists).domain;
                (exists, *param, Post::Expr(render_value(d, Value::PRESENT)))
            }
            Effect::Delete { param } => {
                deleted.push(*param);
                continue;
            }
            Effect::Assign {
                var, param, rhs, ..
            } => {
                let text = match rhs {
                    Rhs::Lit(v) => render_value(&ts.var(*var).domain, *v),
                    Rhs::Param(q) => format!("p{q}"),
                };
                (*var, *param, Post::Expr(text))
            }
            Effect::Transition {
                var, param, arms, ..
            } => {
                let d = &ts.var(*var).domain;
                let cur = format!("{}[p{param}]", names.var(*var));
                let prev = match post.get(var).and_then(|m| m.get(param)) {
                    Some(Post::Expr(e)) => e.clone(),
                    _ => cur.clone(),
                };
                let mut cases: Vec<String> = arms
                    .iter()
                    .map(|(f, t)| {
                        format!("{cur} = {} -> {}", render_value(d, *f), render_value(d, *t))
                    })
                    .collect();
                cases.push(format!("OTHER -> {prev}"));
                (
                    *var,
                    *param,
                    Post::Expr(format!("CASE {}", cases.join(" [] "))),
                )
            }
            Effect::Choose { var, param, values } => (*var, *param, Post::Choose(values.clone())),
            Effect::Tick => {
                tick = true;
                continue;
            }
        };
        let slot = post.entry(var).or_default();
        match (slot.get(&param), &value) {
            (Some(Post::Choose(_)), Post::Expr(_)) => {}
            _ => {
                slot.insert(param, value);
            }
        }
    }
    for &p in &deleted {
        let decl = ts.entity(a.params[usize::from(p)].entity);
        for &v in std::iter::once(&decl.exists)
            .chain(&decl.columns)
            .chain(&decl.owners)
        {
            let d = ts.var(v);
            let value = if v == decl.exists {
                Value::DELETED
            } else {
                d.base
            };
            post.entry(v)
                .or_default()
                .insert(p, Post::Expr(render_value(&d.domain, value)));
        }
    }
    let mut out = Vec::new();
    let mut written = BTreeSet::new();
    let mut fresh = 0;
    for (var, slots) in &post {
        written.insert(*var);
        let name = names.var(*var);
        let mut binders = Vec::new();
        let mut excepts = Vec::new();
        for (p, value) in slots {
            let text = match value {
                Post::Expr(e) => e.clone(),
                Post::Choose(values) => {
                    let x = format!("v{fresh}");
                    fresh += 1;
                    let d = &ts.var(*var).domain;
                    let set: Vec<String> = values.iter().map(|v| render_value(d, *v)).collect();
                    binders.push(format!("{x} \\in {{{}}}", set.join(", ")));
                    x
                }
            };
            excepts.push(format!("![p{p}] = {text}"));
        }
        let assign = format!("{name}' = [{name} EXCEPT {}]", excepts.join(", "));
        out.push(if binders.is_empty() {
            assign
        } else {
            format!("\\E {} : {assign}", binders.join(", "))
        });
    }
    if tick {
        let now = ts.now().expect("tick without a clock");
        written.insert(now);
        out.push("now' = now + 1".to_string());
    }
    (out, written)
}

fn next(ts: &TransitionSystem, names: &TlaNames, out: &mut String) {
    out.push_str("Next ==\n");
    if ts.actions().is_empty() {
        out.push_str("  UNCHANGED vars\n\n");
    } else {
        for id in ts.action_ids() {
            let a = &ts.actions()[id.index()];
            out.push_str(&format!(
                "  \\/ {}{}\n",
                binder(names, a, "\\E"),
                signature(names, id, a)
            ));
        }
        out.push('\n');
    }
    if needs_fairness(ts) {
        out.push_str("Spec == Init /\\ [][Next]_vars /\\ WF_vars(Next)\n\n");
    } else {
        out.push_str("Spec == Init /\\ [][Next]_vars\n\n");
    }
}

/// `\A b0 \in E_Ids, .. : ` and the conjunction that the bound slots are present.
fn binders(ctx: &Ctx, entities: &[EntId]) -> (String, String) {
    if entities.is_empty() {
        return (String::new(), "TRUE".to_string());
    }
    let mut quant = Vec::new();
    let mut present = Vec::new();
    for (k, e) in entities.iter().enumerate() {
        let b = format!("b{k}");
        quant.push(format!("{b} \\in {}", ctx.names.ids(*e)));
        present.push(ctx.present(*e, &b));
    }
    (
        format!("\\A {} : ", quant.join(", ")),
        present.join(" /\\ "),
    )
}

fn closed(
    ts: &TransitionSystem,
    names: &TlaNames,
    entities: &[EntId],
    primed: bool,
    body: &Pred,
) -> String {
    let mut ctx = Ctx {
        ts,
        names,
        primed,
        depth: entities.len() as u8,
    };
    let inner = ctx.pred(body);
    if entities.is_empty() {
        return inner;
    }
    let (quant, present) = binders(&ctx, entities);
    format!("{quant}({present}) => ({inner})")
}

fn checks(ts: &TransitionSystem, names: &TlaNames, out: &mut String) {
    for (i, inv) in ts.invariants().iter().enumerate() {
        out.push_str(&format!(
            "{} == {}\n",
            names.invariant(i),
            closed(ts, names, &inv.binders, false, &inv.body)
        ));
    }
    for (i, a) in ts.after_asserts().iter().enumerate() {
        let post = closed(ts, names, &a.binders, true, &a.post);
        let steps: Vec<String> =
            a.on.iter()
                .map(|id| {
                    let act = &ts.actions()[id.index()];
                    format!(
                        "({}{} => ({post}))",
                        binder(names, act, "\\A"),
                        signature(names, *id, act)
                    )
                })
                .collect();
        out.push_str(&format!(
            "{} == [][{}]_vars\n",
            names.after(i),
            steps.join(" /\\ ")
        ));
    }
    for (i, p) in ts.properties().iter().enumerate() {
        let mut ctx = Ctx {
            ts,
            names,
            primed: false,
            depth: p.binders.len() as u8,
        };
        let (quant, present) = binders(&ctx, &p.binders);
        // A property speaks about an instance once it exists.
        let formula = match &p.formula {
            Ltl::Always(x) => format!("[](({present}) => ({}))", ctx.pred(x)),
            Ltl::Eventually(x) => format!("[](({present}) => <>({}))", ctx.pred(x)),
            Ltl::LeadsTo(x, y) => {
                let (x, y) = (ctx.pred(x), ctx.pred(y));
                format!("(({present}) /\\ ({x})) ~> ({y})")
            }
        };
        out.push_str(&format!("{} == {quant}{formula}\n", names.property(i)));
    }
    if !ts.invariants().is_empty() || !ts.after_asserts().is_empty() || !ts.properties().is_empty()
    {
        out.push('\n');
    }
}
