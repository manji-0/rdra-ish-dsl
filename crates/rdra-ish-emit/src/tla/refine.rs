//! The refinement check of a reduced cone against its unreduced cone, for TLC: a module that
//! extends the unreduced cone's module `C`, instantiates the reduced cone's module `R` with
//! its class var set to the class of each state of `C`, and checks that every reached state
//! of `C` has a class (its key is a state the extended sub-lifecycle reaches) and that every
//! step of `C` is a step of `R` or leaves `R`'s vars alone (docs/theory/tlc-agreement.md,
//! "The reduction, step by step").
//!
//! The class of a state is looked up in a hash table that the module spells out: the key of
//! the state as codes (each var slot's value as `Reduction::key` holds it, then the input
//! bits), hashed the same way here and in TLA+, selects one bucket of `<<codes, class>>`
//! pairs. TLC builds the table once and a lookup costs a pass over the key and one bucket.

use std::collections::{BTreeMap, BTreeSet};

use rdra_ish_core::lifecycle::{Domain, NoClassTable, TransitionSystem, Value, VarKind};

use super::{render_value, TlaBundle};

/// Files of the refinement check: `tla` extends the unreduced cone's module and instantiates
/// the reduced cone's, which TLC must find beside it.
#[derive(Debug, Clone)]
pub struct RefinementBundle {
    pub module_name: String,
    pub tla: String,
    pub cfg: String,
    /// The invariant that every reached state has a class.
    pub reached: String,
    /// The property that every step is a step of the reduced cone or a stutter of it.
    pub steps: String,
    /// The states of the extended sub-lifecycle the table lists.
    pub states: usize,
}

/// The hash of a key's codes: `(h * 31 + code) % buckets`, code by code, which stays far
/// below TLC's 2^31 for any bucket count `print_refinement` picks.
fn hash(codes: &[u8], buckets: usize) -> usize {
    codes
        .iter()
        .fold(0, |h, &c| (h * 31 + usize::from(c)) % buckets)
}

/// The refinement check of `reduced`, a reduced cone, against `c`, the module of the same
/// cone unreduced, and `r`, the module of `reduced`. A cone whose classes
/// `TransitionSystem::class_table` does not list gets its reason instead.
pub fn print_refinement(
    reduced: &TransitionSystem,
    c: &TlaBundle,
    r: &TlaBundle,
    module_name: &str,
) -> Result<RefinementBundle, NoClassTable> {
    let red = reduced.reduction().ok_or(NoClassTable::NotReduced)?;
    let class_var = r.names.class().ok_or(NoClassTable::NotReduced)?;
    let table = reduced.class_table()?;
    let module_name = super::module_name_of(module_name);
    // Every name this module defines starts with a prefix no identifier of `C` starts with,
    // so none hides or repeats one of `C`'s.
    let words: BTreeSet<&str> = c
        .tla
        .split(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '_'))
        .collect();
    let mut prefix = "Ref".to_string();
    while words.iter().any(|w| w.starts_with(&prefix)) || prefix == module_name {
        prefix.push('_');
    }
    let p = |name: &str| format!("{prefix}{name}");

    let mut out = format!(
        "---- MODULE {module_name} ----\n\
         \\* Generated by rdra-ish. Do not edit manually.\n\
         \\* Each state of {cone}, the cone unreduced, mapped to the class of its key in the\n\
         \\* extended sub-lifecycle ({states} states); {reached} says each reached state has one,\n\
         \\* and {steps} that each step is a step of {reduced_mod} or leaves its vars alone.\n\n\
         EXTENDS {cone}, TLC\n\n",
        cone = c.module_name,
        states = table.len(),
        reached = p("Reached"),
        steps = p("Steps"),
        reduced_mod = r.module_name,
    );
    let bits = !red.bits().is_empty();
    if bits {
        // The bits read T alone, so the class the instance is given does not matter.
        out.push_str(&format!(
            "{} == INSTANCE {} WITH {class_var} <- 1\n",
            p("Bits"),
            r.module_name
        ));
    }
    // A value's code: its byte in the state. A domain of strings is looked up in a small
    // function, one per domain; the others are arithmetic on the value TLC holds.
    let mut code_fns: BTreeMap<Vec<String>, String> = BTreeMap::new();
    let mut code_of = |domain: &Domain, value: &str, out: &mut String| -> String {
        match domain {
            Domain::Int => value.to_string(),
            Domain::NullableInt => format!("({value} + 1)"),
            Domain::Instance { optional: true, .. } => value.to_string(),
            Domain::Instance {
                optional: false, ..
            } => format!("({value} - 1)"),
            Domain::Bool => format!("(IF {value} THEN 1 ELSE 0)"),
            _ => {
                let rendered: Vec<String> = (0..domain.size(reduced))
                    .map(|v| render_value(domain, Value::at(v)))
                    .collect();
                let next = code_fns.len();
                let name = code_fns.entry(rendered.clone()).or_insert_with(|| {
                    let name = p(&format!("Code_{next}"));
                    let cells: Vec<String> = rendered
                        .iter()
                        .enumerate()
                        .map(|(k, v)| format!("{v} :> {k}"))
                        .collect();
                    out.push_str(&format!("{name} == {}\n", cells.join(" @@ ")));
                    name
                });
                format!("{name}[{value}]")
            }
        }
    };
    let mut codes: Vec<String> = Vec::new();
    // Per byte of a key, whether the TLA+ key holds it: the stubs' bytes are the same in
    // every state, and are left out.
    let mut kept: Vec<bool> = Vec::new();
    for &v in red.sub_vars() {
        let d = reduced.var(v);
        let name = c.names.var(v);
        match d.kind {
            VarKind::Now => codes.push(code_of(&d.domain, name, &mut out)),
            _ => {
                for k in 1..=reduced.slots_of(&d.kind) {
                    codes.push(code_of(&d.domain, &format!("{name}[{k}]"), &mut out));
                }
            }
        }
        kept.extend(std::iter::repeat_n(true, reduced.slots_of(&d.kind)));
    }
    kept.extend(std::iter::repeat_n(false, red.tail_len()));
    for (g, n) in red.bit_slots(reduced).into_iter().enumerate() {
        for k in 1..=n {
            codes.push(format!("(IF {}!In_{g}({k}) THEN 1 ELSE 0)", p("Bits")));
        }
        kept.extend(std::iter::repeat_n(true, n));
    }
    // A multiple of 31 would keep only the last code of a key.
    let buckets = match table.len().div_ceil(4).max(1) {
        n if n % 31 == 0 => n + 1,
        n => n,
    };
    let mut cells: Vec<Vec<String>> = vec![Vec::new(); buckets];
    for (key, class) in &table {
        assert_eq!(
            key.len(),
            kept.len(),
            "a key is the extended sub-lifecycle's state"
        );
        let key: Vec<u8> = key
            .iter()
            .zip(&kept)
            .filter_map(|(b, k)| k.then_some(*b))
            .collect();
        let tuple: Vec<String> = key.iter().map(u8::to_string).collect();
        cells[hash(&key, buckets)].push(format!("<<<<{}>>, {}>>", tuple.join(", "), class + 1));
    }
    out.push_str(&format!("{} == <<{}>>\n", p("Codes"), codes.join(", ")));
    let steps: Vec<String> = (1..=codes.len())
        .map(|i| {
            let prev = match i {
                1 => "0".to_string(),
                _ => format!("{}H{}", prefix, i - 1),
            };
            format!(
                "{prefix}H{i} == ({prev} * 31 + {}[{i}]) % {buckets}",
                p("Codes")
            )
        })
        .collect();
    out.push_str(&format!(
        "{} == LET {} IN {prefix}H{}\n",
        p("Hash"),
        steps.join("\n    "),
        codes.len()
    ));
    let rows: Vec<String> = cells
        .iter()
        .map(|cell| format!("{{{}}}", cell.join(", ")))
        .collect();
    out.push_str(&format!("{} == <<{}>>\n", p("Table"), rows.join(",\n  ")));
    out.push_str(&format!(
        "\\* 0 for a key the table does not list: a state the extended sub-lifecycle does not reach.\n\
         {class} == LET {m} == {{{q} \\in {table}[{hash} + 1] : {q}[1] = {codes}}}\n\
         \x20   IN IF {m} = {{}} THEN 0 ELSE (CHOOSE {q} \\in {m} : TRUE)[2]\n\
         {inst} == INSTANCE {r} WITH {class_var} <- {class}\n\
         {reached} == {class} # 0\n\
         {steps} == {inst}!Init /\\ [][{inst}!Next]_{inst}!vars\n\
         ====\n",
        class = p("Class"),
        m = p("M"),
        q = p("Q"),
        table = p("Table"),
        hash = p("Hash"),
        codes = p("Codes"),
        inst = p("R"),
        r = r.module_name,
        reached = p("Reached"),
        steps = p("Steps"),
    ));
    // `Init` and `Next` rather than `C`'s `Spec`, whose `WF_vars(Next)` would only slow the
    // check of a safety property.
    let cfg = format!(
        "INIT Init\nNEXT Next\nINVARIANT {}\nPROPERTY {}\nCHECK_DEADLOCK FALSE\n",
        p("Reached"),
        p("Steps")
    );
    Ok(RefinementBundle {
        module_name,
        tla: out,
        cfg,
        reached: p("Reached"),
        steps: p("Steps"),
        states: table.len(),
    })
}

#[cfg(test)]
mod tests {
    use super::hash;

    /// The module's hash, written out for a key of three codes into 7 buckets.
    #[test]
    fn the_hash_is_the_one_the_module_spells() {
        let by_hand = ((9 % 7 * 31 + 3) % 7 * 31 + 1) % 7;
        assert_eq!(hash(&[9, 3, 1], 7), by_hand);
    }
}
