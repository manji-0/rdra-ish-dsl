//! `export --kind sql`: the logical data model as SQL DDL for one dialect.
//!
//! Tables come from `entity` declarations, keys from `@pk`, `@unique`, and `relate`, indexes
//! from `@index` and every foreign key, and `CHECK` constraints from every entity-local rule
//! (`@check`, `forbidden`, `invariant`, `required`, `exclusive`), named as `check` and
//! `verify` name them. A rule reads a comparison with a null operand as false, except `!=`
//! (docs/language-reference.md, "Null"); SQL would read it as unknown, which a `CHECK`
//! accepts, so each comparison is written out with its null case. Rules the schema cannot
//! enforce (several entities, related rows, minimum cardinality, a condition guard, `now`)
//! close the script as a comment, by name.

use std::collections::BTreeSet;

use crate::{EmitError, Emitter, View};
use rdra_ish_core::lifecycle::{Bounds, InvKind, Invariant, ModelRef, Scope, TransitionSystem};
use rdra_ish_core::model::{
    ArithExpr, ArithOperand, CheckExpr, CmpOpModel, CmpRhs, ColumnType, ComparisonProp, DefaultFn,
    DerivedExpr, EffectValue, Entity, EntityKey, ForeignKey, IdGeneration, ModelColumn, RefAction,
    RuleRef, SemanticModel, UniqueSource,
};
use rdra_ish_syntax::ast::ArithOp;

/// The SQL dialect a script is written for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Dialect {
    /// PostgreSQL: `CREATE TYPE ... AS ENUM`, `TIMESTAMPTZ`, foreign keys added after every
    /// table exists.
    Postgres,
    /// SQLite: Enum values as a `CHECK`, temporal columns as ISO-8601 text, foreign keys
    /// inline (SQLite resolves them when it uses them).
    Sqlite,
}

impl Dialect {
    pub fn as_str(self) -> &'static str {
        match self {
            Dialect::Postgres => "postgres",
            Dialect::Sqlite => "sqlite",
        }
    }
}

pub struct SqlEmitter {
    pub dialect: Dialect,
}

/// The rules a schema of `dialect` does not enforce, by the names `check` and `verify` report,
/// each with why: the rules the script's "Not enforced by this schema" comment lists, which
/// the application or a trigger keeps.
pub fn unenforced_rules(model: &SemanticModel, dialect: Dialect) -> Vec<(String, &'static str)> {
    Script::new(model, dialect)
        .obligations()
        .into_iter()
        .map(|r| (r.name, r.why))
        .collect()
}

impl Emitter for SqlEmitter {
    fn emit(&self, model: &SemanticModel, _view: &View) -> Result<String, EmitError> {
        Ok(Script::new(model, self.dialect).document())
    }
}

/// A rule the script enforces as a `CHECK`, or lists as an obligation.
#[derive(Clone)]
pub(crate) struct Rule {
    pub(crate) name: String,
    /// The rule's `.label("...")`.
    pub(crate) label: Option<String>,
    /// `CHECK (...)` body; `None` when the schema cannot enforce the rule.
    check: Option<String>,
    /// Why the schema cannot enforce it.
    pub(crate) why: &'static str,
    /// The rule as the model writes it.
    pub(crate) text: String,
    /// The first entity a rule over several rows binds; `None` for an entity-local rule.
    pub(crate) entity: Option<String>,
}

impl Rule {
    /// `"label": text`, or the text alone for a rule without a label.
    pub(crate) fn described(&self) -> String {
        match &self.label {
            Some(label) => format!("\"{}\": {}", one_line(label), self.text),
            None => self.text.clone(),
        }
    }
}

pub(crate) struct Script<'m> {
    model: &'m SemanticModel,
    dialect: Dialect,
    /// The system `check` builds, for the rule names it prints.
    invariants: Vec<Invariant>,
    /// The system's entity ids, by `EntId`.
    entity_ids: Vec<String>,
}

impl<'m> Script<'m> {
    pub(crate) fn new(model: &'m SemanticModel, dialect: Dialect) -> Self {
        let ts = TransitionSystem::build(model, Bounds::STATES, &Scope::ALL).ts;
        Script {
            model,
            dialect,
            invariants: ts.invariants().to_vec(),
            entity_ids: ts.entities().iter().map(|e| e.id.clone()).collect(),
        }
    }

    /// The rules the schema leaves to the application: each table's rules without a `CHECK`,
    /// table by table, then the rules over several rows.
    fn obligations(&self) -> Vec<Rule> {
        self.entities()
            .into_iter()
            .flat_map(|(key, entity)| self.entity_rules(key, entity))
            .filter(|r| r.check.is_none())
            .chain(self.model_obligations())
            .collect()
    }

    fn entities(&self) -> Vec<(EntityKey, &'m Entity)> {
        let mut entities: Vec<_> = self.model.entities.iter().collect();
        entities.sort_by_key(|(_, e)| e.id.as_str());
        entities
    }

    fn document(&self) -> String {
        let mut out = format!(
            "-- Generated by rdra-ish export --kind sql --dialect {} from the logical data model.\n\
             -- CHECK constraints carry the names check and verify report.\n\n",
            self.dialect.as_str()
        );
        let types = self.enum_types();
        if !types.is_empty() {
            out.push_str(match self.dialect {
                Dialect::Postgres => "-- Types\n\n",
                Dialect::Sqlite => {
                    "-- Value sets: SQLite has no enum type, so each column checks its values.\n\n"
                }
            });
            for ty in types {
                out.push_str(&ty);
                out.push_str("\n\n");
            }
        }
        if !self.model.entities.is_empty() {
            out.push_str("-- Tables\n\n");
        }
        for (key, entity) in self.entities() {
            let rules = self.entity_rules(key, entity);
            out.push_str(&self.table(key, entity, &rules));
            out.push('\n');
            for index in self.indexes(key, entity) {
                out.push_str(&index);
                out.push('\n');
            }
            out.push('\n');
        }
        if self.dialect == Dialect::Postgres {
            let fks: Vec<String> = self
                .entities()
                .into_iter()
                .flat_map(|(key, entity)| {
                    self.foreign_keys(key)
                        .into_iter()
                        .map(move |fk| self.alter_foreign_key(entity, fk))
                })
                .collect();
            if !fks.is_empty() {
                out.push_str("-- Foreign keys\n\n");
                for fk in fks {
                    out.push_str(&fk);
                    out.push('\n');
                }
            }
        }
        out.push_str(&self.reads_section());
        let obligations = self.obligations();
        if !obligations.is_empty() {
            out.push_str(
                "\n-- Not enforced by this schema: the application or a trigger keeps these rules.\n",
            );
            for rule in obligations {
                out.push_str(&format!(
                    "-- {} ({}): {}\n",
                    rule.name,
                    rule.why,
                    rule.described()
                ));
            }
        }
        while out.ends_with("\n\n") {
            out.pop();
        }
        out
    }

    // ── Types ───────────────────────────────────────────────────────────────

    /// PostgreSQL: a `CREATE TYPE` per inline Enum column and per variation, a variation's
    /// under a comment with its label and its values' labels. SQLite: that comment alone
    /// per variation, since its columns check their values.
    fn enum_types(&self) -> Vec<String> {
        let mut types = Vec::new();
        if self.dialect == Dialect::Postgres {
            for (_, entity) in self.entities() {
                for column in &entity.columns {
                    if let ColumnType::Enum(values) = &column.col_type {
                        types.push(create_enum(&enum_type_name(entity, column), values));
                    }
                }
            }
        }
        let mut variations: Vec<_> = self.model.variations.values().collect();
        variations.sort_by_key(|v| v.id.as_str());
        for variation in variations {
            let note = variation_note(variation);
            types.push(match self.dialect {
                Dialect::Postgres => {
                    format!(
                        "{note}\n{}",
                        create_enum(&variation.id, &variation.value_names())
                    )
                }
                Dialect::Sqlite => note,
            });
        }
        types
    }

    fn column_type(&self, entity: &Entity, column: &ModelColumn) -> String {
        let pg = self.dialect == Dialect::Postgres;
        let detail = column.detail;
        match &column.col_type {
            ColumnType::Int => "INTEGER".to_string(),
            ColumnType::String => match detail.length {
                Some(n) => format!("VARCHAR({n})"),
                None => "TEXT".to_string(),
            },
            ColumnType::Money | ColumnType::Decimal => match (detail.precision, detail.scale) {
                (Some(p), Some(s)) => format!("NUMERIC({p}, {s})"),
                _ => "NUMERIC".to_string(),
            },
            ColumnType::DateTime if pg && detail.time_zone == Some(false) => {
                "TIMESTAMP".to_string()
            }
            ColumnType::DateTime if pg => "TIMESTAMPTZ".to_string(),
            ColumnType::Date if pg => "DATE".to_string(),
            ColumnType::DateTime | ColumnType::Date => "TEXT".to_string(),
            ColumnType::Bool => "BOOLEAN".to_string(),
            ColumnType::Enum(_) if pg => ident(&enum_type_name(entity, column)),
            ColumnType::Variation(key) if pg => self
                .model
                .variations
                .get(*key)
                .map_or_else(|| "TEXT".to_string(), |v| ident(&v.id)),
            ColumnType::Enum(_) | ColumnType::Variation(_) => "TEXT".to_string(),
        }
    }

    /// The values of an Enum or variation column, for SQLite's `CHECK (col IN (...))`.
    fn enum_values(&self, column: &ModelColumn) -> Option<Vec<String>> {
        match &column.col_type {
            ColumnType::Enum(values) => Some(values.clone()),
            ColumnType::Variation(key) => self.model.variations.get(*key).map(|v| v.value_names()),
            _ => None,
        }
    }

    // ── Tables ──────────────────────────────────────────────────────────────

    fn table(&self, key: EntityKey, entity: &Entity, rules: &[Rule]) -> String {
        let mut lines: Vec<String> = entity
            .columns
            .iter()
            .map(|c| self.column_def(entity, c))
            .collect();
        if !entity.primary_key.is_empty() {
            lines.push(format!("PRIMARY KEY ({})", idents(&entity.primary_key)));
        }
        for unique in self.unique_sets(key, entity) {
            if self.live_predicate(key, entity, &unique).is_none() {
                lines.push(format!("UNIQUE ({})", idents(&unique)));
            }
        }
        if self.dialect == Dialect::Sqlite {
            for column in &entity.columns {
                if let Some(values) = self.enum_values(column) {
                    lines.push(format!(
                        "CONSTRAINT {} CHECK ({} IN ({}))",
                        ident(&format!("{}_{}_values", entity.table_name(), column.name)),
                        ident(&column.name),
                        values
                            .iter()
                            .map(|v| string(v))
                            .collect::<Vec<_>>()
                            .join(", ")
                    ));
                }
            }
            for fk in self.foreign_keys(key) {
                lines.push(self.foreign_key_clause(entity, fk));
            }
        }
        for rule in rules {
            if let Some(check) = &rule.check {
                let constraint = format!("CONSTRAINT {} CHECK ({check})", ident(&rule.name));
                lines.push(match &rule.label {
                    Some(label) => format!("-- {}\n  {constraint}", one_line(label)),
                    None => constraint,
                });
            }
        }
        let mut out = String::new();
        let note = table_note(entity);
        if !note.is_empty() {
            out.push_str(&format!("-- {note}\n"));
        }
        out.push_str(&format!("CREATE TABLE {} (\n", ident(entity.table_name())));
        out.push_str(
            &lines
                .iter()
                .map(|l| format!("  {l}"))
                .collect::<Vec<_>>()
                .join(",\n"),
        );
        out.push_str("\n);");
        out
    }

    fn column_def(&self, entity: &Entity, column: &ModelColumn) -> String {
        let mut def = format!(
            "{} {}",
            ident(&column.name),
            self.column_type(entity, column)
        );
        if let Some(expr) = &column.derived_expr {
            if let Some(sql) = self.derived(entity, expr) {
                let storage = match self.dialect {
                    Dialect::Postgres => "STORED",
                    Dialect::Sqlite => "VIRTUAL",
                };
                def.push_str(&format!(" GENERATED ALWAYS AS ({sql}) {storage}"));
            }
            return with_note(def, column);
        }
        if !column.is_nullable {
            def.push_str(" NOT NULL");
        }
        let (computed, note) = self.computed(column);
        if let Some(clause) = computed {
            def.push_str(&format!(" {clause}"));
        } else if let Some(default) = column.default_val.as_deref() {
            if let Some(value) = self.default_literal(column, default) {
                def.push_str(&format!(" DEFAULT {value}"));
            }
        }
        let def = with_note(def, column);
        match note {
            Some(note) if def.ends_with(" */") => {
                format!("{}; {note} */", &def[..def.len() - 3])
            }
            Some(note) => format!("{def} /* {note} */"),
            None => def,
        }
    }

    /// What the database computes for the column (`@generated`, `@default(now())`), as a
    /// clause; and, when the dialect has no clause for it, what the application does.
    fn computed(&self, column: &ModelColumn) -> (Option<String>, Option<String>) {
        let pg = self.dialect == Dialect::Postgres;
        if column.is_version {
            // Optimistic locking: `UPDATE ... SET v = v + 1 WHERE id = ? AND v = ?`.
            let note = "version: each update checks it and adds 1".to_string();
            let clause = column
                .default_val
                .is_none()
                .then(|| "DEFAULT 1".to_string());
            return (clause, Some(note));
        }
        let mut note = column
            .on_update
            .map(|f| format!("on update: {} (trigger or application)", f.as_str()));
        let clause = match (column.generated, column.default_fn) {
            (Some(IdGeneration::Identity), _) if pg => {
                Some("GENERATED BY DEFAULT AS IDENTITY".to_string())
            }
            (Some(IdGeneration::Identity), _) => {
                // A single INTEGER primary key is the rowid, which SQLite numbers.
                None
            }
            (Some(IdGeneration::Uuid), _) | (None, Some(DefaultFn::Uuid)) if pg => {
                Some("DEFAULT gen_random_uuid()::text".to_string())
            }
            (Some(how), _) => {
                note = Some(join_notes(
                    note,
                    format!("{} generated by the application", how.as_str()),
                ));
                None
            }
            (None, Some(DefaultFn::Uuid)) => {
                note = Some(join_notes(
                    note,
                    "default: uuid() by the application".to_string(),
                ));
                None
            }
            (None, Some(DefaultFn::Now)) => Some(match column.col_type {
                ColumnType::Date => "DEFAULT CURRENT_DATE".to_string(),
                _ => "DEFAULT CURRENT_TIMESTAMP".to_string(),
            }),
            (None, None) => None,
        };
        (clause, note)
    }

    fn default_literal(&self, column: &ModelColumn, default: &str) -> Option<String> {
        if default == "null" {
            return None;
        }
        Some(match &column.col_type {
            ColumnType::Bool => match default.to_ascii_lowercase().as_str() {
                "true" => "TRUE".to_string(),
                "false" => "FALSE".to_string(),
                _ => return None,
            },
            ColumnType::Int | ColumnType::Money | ColumnType::Decimal
                if default.parse::<f64>().is_ok() =>
            {
                default.to_string()
            }
            _ => string(default),
        })
    }

    /// Composite unique sets and single-column `@unique`, each once, in column order.
    fn unique_sets(&self, key: EntityKey, entity: &Entity) -> Vec<Vec<String>> {
        let mut sets: Vec<Vec<String>> = entity
            .columns
            .iter()
            .filter(|c| c.is_unique && !(entity.primary_key == [c.name.clone()]))
            .map(|c| vec![c.name.clone()])
            .collect();
        for unique in self.model.unique_keys(key) {
            if !sets.iter().any(|s| same_set(s, &unique.columns)) {
                sets.push(unique.columns.clone());
            }
        }
        sets
    }

    fn indexes(&self, key: EntityKey, entity: &Entity) -> Vec<String> {
        let mut covered: Vec<Vec<String>> = Vec::new();
        if !entity.primary_key.is_empty() {
            covered.push(entity.primary_key.clone());
        }
        let mut live = Vec::new();
        for unique in self.unique_sets(key, entity) {
            match self.live_predicate(key, entity, &unique) {
                // A partial index does not hold every row, so it covers no foreign key.
                Some(pred) => live.push(format!(
                    "CREATE UNIQUE INDEX {} ON {} ({}) WHERE {pred};",
                    ident(&format!(
                        "{}_{}_live_key",
                        entity.table_name(),
                        unique.join("_")
                    )),
                    ident(entity.table_name()),
                    idents(&unique)
                )),
                None => covered.push(unique),
            }
        }
        let mut wanted: Vec<Vec<String>> = Vec::new();
        for columns in &entity.indexes {
            if !wanted.contains(columns) {
                wanted.push(columns.clone());
            }
        }
        // A foreign key is read on every join and on each delete of its parent.
        for fk in self.foreign_keys(key) {
            let columns: Vec<String> = fk.columns.iter().map(|(c, _)| c.clone()).collect();
            let has_prefix = |set: &Vec<String>| set.starts_with(&columns);
            if !covered.iter().any(has_prefix) && !wanted.iter().any(has_prefix) {
                wanted.push(columns);
            }
        }
        live.extend(wanted.into_iter().map(|columns| {
            format!(
                "CREATE INDEX {} ON {} ({});",
                ident(&format!(
                    "{}_{}_idx",
                    entity.table_name(),
                    columns.join("_")
                )),
                ident(entity.table_name()),
                idents(&columns)
            )
        }));
        live
    }

    /// On an entity with a `@soft_delete` column, a declared unique set holds among the rows
    /// not deleted: the condition a partial unique index keeps them by. `None` for a key a
    /// relate makes (1:1, junction) or one a foreign key references, which hold over every
    /// row, and on an entity without the marker.
    fn live_predicate(&self, key: EntityKey, entity: &Entity, set: &[String]) -> Option<String> {
        let marker = entity.columns.iter().find(|c| c.is_soft_delete)?;
        let made_by_relate =
            self.model.foreign_keys().any(|(_, fk)| {
                fk.child == key && fk.unique() && same_set(&fk_child_columns(fk), set)
            }) || self
                .model
                .unique_keys(key)
                .iter()
                .any(|u| same_set(&u.columns, set) && u.source != UniqueSource::Declared);
        let referenced = self.model.foreign_keys().any(|(_, fk)| {
            fk.parent == key
                && same_set(
                    &fk.columns
                        .iter()
                        .map(|(_, p)| p.clone())
                        .collect::<Vec<_>>(),
                    set,
                )
        });
        if made_by_relate || referenced {
            return None;
        }
        live_condition(marker)
    }

    // ── Foreign keys ────────────────────────────────────────────────────────

    fn foreign_keys(&self, key: EntityKey) -> Vec<&'m ForeignKey> {
        self.model
            .foreign_keys()
            .map(|(_, fk)| fk)
            .filter(|fk| fk.child == key && !fk.columns.is_empty())
            .collect()
    }

    fn foreign_key_clause(&self, entity: &Entity, fk: &ForeignKey) -> String {
        let parent = &self.model.entities[fk.parent];
        let child_cols: Vec<String> = fk.columns.iter().map(|(c, _)| c.clone()).collect();
        let parent_cols: Vec<String> = fk.columns.iter().map(|(_, p)| p.clone()).collect();
        let mut clause = format!(
            "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
            ident(&format!(
                "{}_{}_fkey",
                entity.table_name(),
                child_cols.join("_")
            )),
            idents(&child_cols),
            ident(parent.table_name()),
            idents(&parent_cols)
        );
        if let Some(action) = fk.on_delete {
            clause.push_str(&format!(" ON DELETE {}", ref_action(action)));
        }
        if let Some(action) = fk.on_update {
            clause.push_str(&format!(" ON UPDATE {}", ref_action(action)));
        }
        clause
    }

    fn alter_foreign_key(&self, entity: &Entity, fk: &ForeignKey) -> String {
        format!(
            "ALTER TABLE {} ADD {};",
            ident(entity.table_name()),
            self.foreign_key_clause(entity, fk)
        )
    }

    // ── Rules ───────────────────────────────────────────────────────────────

    /// The name `check` gives the invariant built from `fact`, or `fallback`.
    /// The name `check` gives the rule declared at `fact`, and its label.
    fn rule_name(&self, fact: &ModelRef, fallback: String) -> (String, Option<String>) {
        self.invariants
            .iter()
            .find(|inv| inv.site.fact == *fact)
            .map_or((fallback, None), |inv| {
                (inv.name.clone(), inv.label.clone())
            })
    }

    fn guarded(&self, rule: RuleRef) -> bool {
        self.model.rule_guards.iter().any(|g| g.rule == rule)
    }

    pub(crate) fn entity_rules(&self, key: EntityKey, entity: &Entity) -> Vec<Rule> {
        let model = self.model;
        let mut rules = Vec::new();
        for column in &entity.columns {
            let fact = ModelRef::Column {
                entity: key,
                column: column.name.clone(),
            };
            let names: Vec<&Invariant> = self
                .invariants
                .iter()
                .filter(|inv| inv.text.kind() == InvKind::Check && inv.site.fact == fact)
                .collect();
            for (i, check) in column.check_constraints.iter().enumerate() {
                let name = names.get(i).map_or_else(
                    || (format!("Check_{}_{}_{i}", entity.id, column.name), None),
                    |inv| (inv.name.clone(), inv.label.clone()),
                );
                rules.push(self.rule(
                    name,
                    self.check_expr(entity, &check.expr),
                    check.expr.display(),
                    false,
                ));
            }
        }
        for (i, c) in model.forbidden_constraints.iter().enumerate() {
            if c.entity != key {
                continue;
            }
            let name = self.rule_name(
                &ModelRef::Forbidden(i),
                format!("Forbidden_{}_{i}", entity.id),
            );
            let conds = self.conjuncts(entity, &c.conditions, &c.comparisons);
            let check = conds.map(|c| format!("NOT ({})", and(&c)));
            let text = local_text(&c.conditions, &c.comparisons);
            rules.push(self.rule(name, check, text, self.guarded(RuleRef::Forbidden(i))));
        }
        for (i, c) in model.entity_invariants.iter().enumerate() {
            if c.entity != key {
                continue;
            }
            let name = self.rule_name(
                &ModelRef::EntityInvariant(i),
                format!("Inv_{}_{i}", entity.id),
            );
            let guards = self.conjuncts(entity, &c.guards, &c.guard_comparisons);
            let reqs = self.conjuncts(entity, &c.requireds, &c.required_comparisons);
            let check = match (guards, reqs) {
                (Some(g), Some(r)) if !g.is_empty() => {
                    Some(format!("NOT ({}) OR ({})", and(&g), and(&r)))
                }
                (Some(_), Some(r)) => Some(and(&r)),
                _ => None,
            };
            let text = format!(
                "when {} then {}",
                local_text(&c.guards, &c.guard_comparisons),
                local_text(&c.requireds, &c.required_comparisons)
            );
            rules.push(self.rule(name, check, text, self.guarded(RuleRef::Invariant(i))));
        }
        for (i, c) in model.required_constraints.iter().enumerate() {
            if c.entity != key {
                continue;
            }
            let name = self.rule_name(
                &ModelRef::Required(i),
                format!("Required_{}_{i}", entity.id),
            );
            let check = self
                .conjuncts(entity, &c.conditions, &c.comparisons)
                .map(|c| and(&c));
            let text = local_text(&c.conditions, &c.comparisons);
            rules.push(self.rule(name, check, text, false));
        }
        for (i, c) in model.exclusive_constraints.iter().enumerate() {
            if c.entity != key {
                continue;
            }
            let name = self.rule_name(
                &ModelRef::Exclusive(i),
                format!("Exclusive_{}_{i}", entity.id),
            );
            // At most one of the conditions holds.
            let check = self
                .conjuncts(entity, &c.conditions, &c.comparisons)
                .map(|conds| {
                    let terms: Vec<String> = conds
                        .iter()
                        .map(|c| format!("(CASE WHEN {c} THEN 1 ELSE 0 END)"))
                        .collect();
                    format!("{} <= 1", terms.join(" + "))
                });
            let text = local_text(&c.conditions, &c.comparisons);
            rules.push(self.rule(name, check, text, false));
        }
        rules
    }

    fn rule(
        &self,
        (name, label): (String, Option<String>),
        check: Option<String>,
        text: String,
        guarded: bool,
    ) -> Rule {
        let (check, why) = match (check, guarded) {
            (_, true) => (None, "guarded by a condition"),
            (None, false) => (None, "reads now"),
            (Some(c), false) => (Some(c), ""),
        };
        Rule {
            name,
            label,
            check,
            why,
            text,
            entity: None,
        }
    }

    /// The rules over several rows, by the names `check` gives them.
    pub(crate) fn model_obligations(&self) -> Vec<Rule> {
        self.invariants
            .iter()
            .filter_map(|inv| {
                let why = match inv.text.kind() {
                    InvKind::CrossForbidden | InvKind::CrossInvariant => "several entities",
                    InvKind::Quantifier => "related rows",
                    InvKind::MinCard => "minimum cardinality",
                    _ => return None,
                };
                let ts_entity = inv
                    .binders
                    .first()
                    .map(|e| self.entity_ids[e.index()].clone());
                Some(Rule {
                    name: inv.name.clone(),
                    label: inv.label.clone(),
                    check: None,
                    why,
                    text: inv_text(inv),
                    entity: ts_entity,
                })
            })
            .collect()
    }

    /// Each equality and comparison as a two-valued SQL condition; `None` when one reads `now`.
    fn conjuncts(
        &self,
        entity: &Entity,
        equalities: &[(String, EffectValue)],
        comparisons: &[ComparisonProp],
    ) -> Option<Vec<String>> {
        let mut out = Vec::new();
        for (column, value) in equalities {
            out.push(self.compare(
                entity,
                column,
                CmpOpModel::Eq,
                &CmpRhs::Value(value.clone()),
            )?);
        }
        for prop in comparisons {
            out.push(self.compare(entity, &prop.lhs_column, prop.op, &prop.rhs)?);
        }
        Some(out)
    }

    fn check_expr(&self, entity: &Entity, expr: &CheckExpr) -> Option<String> {
        Some(match expr {
            CheckExpr::Cmp(p) => self.compare(entity, &p.lhs_column, p.op, &p.rhs)?,
            CheckExpr::Not(inner) => format!("NOT ({})", self.check_expr(entity, inner)?),
            CheckExpr::And(a, b) => format!(
                "({}) AND ({})",
                self.check_expr(entity, a)?,
                self.check_expr(entity, b)?
            ),
            CheckExpr::Or(a, b) => format!(
                "({}) OR ({})",
                self.check_expr(entity, a)?,
                self.check_expr(entity, b)?
            ),
        })
    }

    fn nullable(&self, entity: &Entity, column: &str) -> bool {
        entity
            .columns
            .iter()
            .find(|c| c.name == column)
            .is_none_or(|c| c.is_nullable || c.derived_expr.is_some())
    }

    /// `lhs op rhs` as a rule reads it: a null operand satisfies `!=` and nothing else.
    fn compare(&self, entity: &Entity, lhs: &str, op: CmpOpModel, rhs: &CmpRhs) -> Option<String> {
        let col = ident(lhs);
        let lhs_null = self.nullable(entity, lhs);
        Some(match rhs {
            CmpRhs::Now => return None,
            // A list of plain values is `IN (...)`; a null `col` is in no list and outside
            // every one, as `==` and `!=` read it.
            CmpRhs::Values(values)
                if values.iter().all(|v| {
                    !matches!(
                        v.normalize(),
                        EffectValue::Null | EffectValue::Present | EffectValue::TypedPresent(_)
                    )
                }) =>
            {
                let list: Vec<String> = values.iter().map(literal).collect();
                let list = list.join(", ");
                match (op, lhs_null) {
                    (CmpOpModel::NotIn, false) => format!("{col} NOT IN ({list})"),
                    (CmpOpModel::NotIn, true) => {
                        format!("({col} IS NULL OR {col} NOT IN ({list}))")
                    }
                    (_, false) => format!("{col} IN ({list})"),
                    (_, true) => format!("({col} IS NOT NULL AND {col} IN ({list}))"),
                }
            }
            CmpRhs::Values(values) => {
                let (each, join) = match op {
                    CmpOpModel::NotIn => (CmpOpModel::Ne, " AND "),
                    _ => (CmpOpModel::Eq, " OR "),
                };
                let parts: Option<Vec<String>> = values
                    .iter()
                    .map(|v| self.compare(entity, lhs, each, &CmpRhs::Value(v.clone())))
                    .collect();
                format!("({})", parts?.join(join))
            }
            CmpRhs::Value(EffectValue::Null) => match op {
                CmpOpModel::Ne => format!("{col} IS NOT NULL"),
                _ => format!("{col} IS NULL"),
            },
            CmpRhs::Value(EffectValue::Present | EffectValue::TypedPresent(_)) => match op {
                CmpOpModel::Ne => format!("{col} IS NULL"),
                _ => format!("{col} IS NOT NULL"),
            },
            CmpRhs::Value(v) => guard_nulls(&[(&col, lhs_null)], op, &col, &literal(v)),
            CmpRhs::IntLit(n) => guard_nulls(&[(&col, lhs_null)], op, &col, &n.to_string()),
            CmpRhs::Column(other) => {
                let rcol = ident(other);
                let rhs_null = self.nullable(entity, other);
                guard_nulls(&[(&col, lhs_null), (&rcol, rhs_null)], op, &col, &rcol)
            }
        })
    }

    /// A `@derived` expression, read with SQL's three-valued logic, which is the meaning a
    /// derived value has (docs/state-derivation.md); `None` when it reads `now`, which a
    /// generated column cannot.
    fn derived(&self, entity: &Entity, expr: &DerivedExpr) -> Option<String> {
        match expr {
            DerivedExpr::Arith(ArithExpr { lhs, op, rhs }) => {
                let op = match op {
                    ArithOp::Add => "+",
                    ArithOp::Sub => "-",
                    ArithOp::Mul => "*",
                };
                Some(format!("{} {op} {}", operand(lhs), operand(rhs)))
            }
            DerivedExpr::Logical(expr) => self.sql_logic(entity, expr),
        }
    }

    fn sql_logic(&self, entity: &Entity, expr: &CheckExpr) -> Option<String> {
        Some(match expr {
            CheckExpr::Cmp(p) => {
                let col = ident(&p.lhs_column);
                match &p.rhs {
                    CmpRhs::Now => return None,
                    CmpRhs::Column(c) => format!("{col} {} {}", sql_op(p.op), ident(c)),
                    CmpRhs::IntLit(n) => format!("{col} {} {n}", sql_op(p.op)),
                    CmpRhs::Values(vs) => format!(
                        "{col} {} ({})",
                        if p.op == CmpOpModel::NotIn {
                            "NOT IN"
                        } else {
                            "IN"
                        },
                        vs.iter().map(literal).collect::<Vec<_>>().join(", ")
                    ),
                    CmpRhs::Value(EffectValue::Null) | CmpRhs::Value(EffectValue::Present) => {
                        return self.compare(entity, &p.lhs_column, p.op, &p.rhs)
                    }
                    CmpRhs::Value(v) => format!("{col} {} {}", sql_op(p.op), literal(v)),
                }
            }
            CheckExpr::Not(inner) => format!("NOT ({})", self.sql_logic(entity, inner)?),
            CheckExpr::And(a, b) => format!(
                "({}) AND ({})",
                self.sql_logic(entity, a)?,
                self.sql_logic(entity, b)?
            ),
            CheckExpr::Or(a, b) => format!(
                "({}) OR ({})",
                self.sql_logic(entity, a)?,
                self.sql_logic(entity, b)?
            ),
        })
    }
}

/// `col op value`, false when a nullable operand is null, except `!=`, which is then true.
fn guard_nulls(nullable: &[(&String, bool)], op: CmpOpModel, lhs: &str, rhs: &str) -> String {
    let nulls: Vec<&String> = nullable
        .iter()
        .filter(|(_, n)| *n)
        .map(|(c, _)| *c)
        .collect();
    let cmp = format!("{lhs} {} {rhs}", sql_op(op));
    if nulls.is_empty() {
        return cmp;
    }
    if op == CmpOpModel::Ne {
        let mut parts: Vec<String> = nulls.iter().map(|c| format!("{c} IS NULL")).collect();
        parts.push(cmp);
        format!("({})", parts.join(" OR "))
    } else {
        let mut parts: Vec<String> = nulls.iter().map(|c| format!("{c} IS NOT NULL")).collect();
        parts.push(cmp);
        format!("({})", parts.join(" AND "))
    }
}

fn sql_op(op: CmpOpModel) -> &'static str {
    match op {
        CmpOpModel::Lt => "<",
        CmpOpModel::Gt => ">",
        CmpOpModel::Le => "<=",
        CmpOpModel::Ge => ">=",
        CmpOpModel::Eq | CmpOpModel::In => "=",
        CmpOpModel::Ne | CmpOpModel::NotIn => "<>",
    }
}

fn and(parts: &[String]) -> String {
    if parts.is_empty() {
        "TRUE".to_string()
    } else {
        parts.join(" AND ")
    }
}

fn literal(value: &EffectValue) -> String {
    match value.normalize() {
        EffectValue::EnumVariant(v) => string(v),
        EffectValue::Bool(true) => "TRUE".to_string(),
        EffectValue::Bool(false) => "FALSE".to_string(),
        EffectValue::Int(n) => n.to_string(),
        EffectValue::Null => "NULL".to_string(),
        EffectValue::Present | EffectValue::TypedPresent(_) => "NULL".to_string(),
    }
}

fn operand(operand: &ArithOperand) -> String {
    match operand {
        ArithOperand::Column(c) => ident(c),
        ArithOperand::Int(n) => n.to_string(),
    }
}

fn local_text(equalities: &[(String, EffectValue)], comparisons: &[ComparisonProp]) -> String {
    equalities
        .iter()
        .map(|(c, v)| format!("{c} == {}", v.literal()))
        .chain(comparisons.iter().map(ComparisonProp::display))
        .collect::<Vec<_>>()
        .join(", ")
}

fn inv_text(inv: &Invariant) -> String {
    use rdra_ish_core::lifecycle::InvText;
    match &inv.text {
        InvText::Forbidden(c)
        | InvText::Required(c)
        | InvText::Exclusive(c)
        | InvText::Check(c) => c.clone(),
        InvText::Invariant { guards, requireds } => format!("when {guards} then {requireds}"),
        InvText::CrossForbidden {
            entities,
            conditions,
        } => format!("{entities}: {conditions}"),
        InvText::CrossInvariant {
            entities,
            guards,
            requireds,
        } => format!("{entities}: when {guards} then {requireds}"),
        InvText::Quantifier {
            anchor, constraint, ..
        } => format!("{anchor}: {constraint}"),
        InvText::Unique {
            child,
            parent,
            role,
        }
        | InvText::MinCard {
            child,
            parent,
            role,
        } => format!("{child} -> {parent} ({role})"),
    }
}

fn fk_child_columns(fk: &ForeignKey) -> Vec<String> {
    fk.columns.iter().map(|(c, _)| c.clone()).collect()
}

fn join_notes(note: Option<String>, more: String) -> String {
    match note {
        Some(n) => format!("{n}; {more}"),
        None => more,
    }
}

fn with_note(def: String, column: &ModelColumn) -> String {
    let mut notes = Vec::new();
    if let Some(label) = &column.label {
        notes.push(label.clone());
    }
    if column.is_soft_delete {
        notes.push("soft delete marker".to_string());
    }
    if column.is_history {
        notes.push("history/versioning marker".to_string());
    }
    if column.is_tenant_scope {
        notes.push("tenant scope discriminator".to_string());
    }
    if let Some(expr) = &column.derived_expr {
        notes.push(format!("derived: {}", expr.display()));
    }
    if notes.is_empty() {
        def
    } else {
        format!("{def} /* {} */", notes.join("; ").replace("*/", "* /"))
    }
}

fn table_note(entity: &Entity) -> String {
    let mut note = entity.label.clone();
    if let Some(description) = &entity.description {
        if !description.trim().is_empty() {
            note.push_str(": ");
            note.push_str(description.trim());
        }
    }
    note.replace('\n', " ")
}

/// One line: a label or description may hold a line break, which would end a `--` comment.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// `-- PaymentMethod (支払方法): cash = 現金, card`: a variation's label and its values'.
fn variation_note(variation: &rdra_ish_core::model::Variation) -> String {
    let values: Vec<String> = variation
        .values
        .iter()
        .map(|v| match &v.label {
            Some(label) => format!("{} = {}", v.value, one_line(label)),
            None => v.value.clone(),
        })
        .collect();
    format!(
        "-- {} ({}): {}",
        variation.id,
        one_line(&variation.label),
        values.join(", ")
    )
}

fn create_enum(name: &str, values: &[String]) -> String {
    format!(
        "CREATE TYPE {} AS ENUM ({});",
        ident(name),
        values
            .iter()
            .map(|v| string(v))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn enum_type_name(entity: &Entity, column: &ModelColumn) -> String {
    format!("{}_{}", entity.id, column.name)
}

fn ref_action(action: RefAction) -> String {
    action.as_str().replace('_', " ").to_ascii_uppercase()
}

/// The condition a row not soft-deleted meets: the marker is null, or `FALSE` for a `Bool`.
fn live_condition(marker: &ModelColumn) -> Option<String> {
    let col = ident(&marker.name);
    match marker.col_type {
        ColumnType::Bool => Some(format!("{col} = FALSE")),
        _ if marker.is_nullable => Some(format!("{col} IS NULL")),
        _ => None,
    }
}

fn same_set(a: &[String], b: &[String]) -> bool {
    let a: BTreeSet<&String> = a.iter().collect();
    let b: BTreeSet<&String> = b.iter().collect();
    a == b
}

fn ident(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

fn idents(names: &[String]) -> String {
    names
        .iter()
        .map(|n| ident(n))
        .collect::<Vec<_>>()
        .join(", ")
}

fn string(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

