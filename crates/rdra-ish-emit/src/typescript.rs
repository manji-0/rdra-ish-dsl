//! TypeScript discriminated-union emitters for entity lifecycle states.

use crate::{EmitError, Explored, OnDeadlock, Scope, StatesEmitter, View};
use rdra_ish_core::{
    collect_entity_state_variants, lifecycle::Caps, model::ColumnType, EntityStateVariant,
    EntityStateVariants, SemanticModel, StateFieldValue,
};

pub struct TypeScriptStateUnionEmitter {
    pub caps: Caps,
}

impl Default for TypeScriptStateUnionEmitter {
    fn default() -> Self {
        Self { caps: Caps::STATES }
    }
}

impl StatesEmitter for TypeScriptStateUnionEmitter {
    fn on_deadlock(&self) -> OnDeadlock {
        OnDeadlock::Refuse
    }

    fn emit(
        &self,
        model: &SemanticModel,
        view: &View,
        _explored: &Explored,
    ) -> Result<String, EmitError> {
        let buc_filter = match &view.scope {
            Scope::Bucs(ids) => ids.clone(),
            Scope::Whole | Scope::UseCases(_) => vec![],
        };
        let collections = collect_entity_state_variants(model, &buc_filter, self.caps);
        Ok(emit_typescript_state_unions(model, &collections))
    }
}

/// The unions of `collections`. `model` gives each column its declared type: a state axis
/// is abstract (an Int is one of the bounded values, a nullable column is `present`), and
/// the union types it by the column, not by the abstract value.
pub fn emit_typescript_state_unions(
    model: &SemanticModel,
    collections: &[EntityStateVariants],
) -> String {
    let mut out = String::from("// Generated by rdra-ish. Do not edit manually.\n\n");
    for collection in collections {
        if collection.variants.is_empty() {
            continue;
        }
        out.push_str(&emit_entity_union(model, collection));
        out.push('\n');
    }
    out
}

fn emit_entity_union(model: &SemanticModel, collection: &EntityStateVariants) -> String {
    let type_name = to_pascal_case(&collection.entity_id);
    let mut out = format!(
        "/** Reachable state variants for {}. */\n",
        collection.entity_id
    );
    out.push_str(&format!("export type {type_name} =\n"));

    // Patterns that differ only in a value the column type does not tell apart (two Int
    // values) print the same object; print it once.
    let mut objects: Vec<String> = Vec::new();
    for variant in &collection.variants {
        let object = emit_variant_object(model, collection, variant);
        if !objects.contains(&object) {
            objects.push(object);
        }
    }
    for (index, object) in objects.iter().enumerate() {
        let prefix = if index == 0 { "  " } else { "  | " };
        out.push_str(prefix);
        out.push_str(object);
        out.push('\n');
    }
    out.push_str(";\n");
    out
}

fn emit_variant_object(
    model: &SemanticModel,
    collection: &EntityStateVariants,
    variant: &EntityStateVariant,
) -> String {
    let mut lines = vec![format!(
        "{}: {};",
        collection.discriminator_column,
        ts_string_literal(&variant.discriminator)
    )];

    for (column, value) in &variant.fields {
        let declared = model
            .entities
            .get(collection.entity)
            .and_then(|e| e.columns.iter().find(|c| c.name == *column))
            .map(|c| &c.col_type);
        lines.push(format!(
            "{column}: {};",
            ts_type_for_field(model, value, declared)
        ));
    }

    if lines.len() == 1 {
        return format!("{{ {} }}", lines[0]);
    }

    let body = lines
        .into_iter()
        .map(|line| format!("    {line}"))
        .collect::<Vec<_>>()
        .join("\n");
    format!("{{\n{body}\n  }}")
}

fn ts_type_for_field(
    model: &SemanticModel,
    value: &StateFieldValue,
    declared: Option<&ColumnType>,
) -> String {
    match value {
        StateFieldValue::Enum(variant) => ts_string_literal(variant),
        StateFieldValue::Bool(_) => "boolean".to_string(),
        StateFieldValue::Null => "null".to_string(),
        // The value is one of the bounded domain `0..=int_max`, not a fact of the row.
        StateFieldValue::Int(_) => "number".to_string(),
        StateFieldValue::Present { pg_type } => match pg_type.as_deref() {
            Some("timestamptz" | "timestamp" | "date") => "Date".to_string(),
            Some("uuid") => "string".to_string(),
            Some("json" | "jsonb") => "Record<string, unknown>".to_string(),
            Some("money" | "decimal") => "number".to_string(),
            Some(_) => "string".to_string(),
            None => declared.map_or_else(|| "unknown".to_string(), |t| ts_column_type(model, t)),
        },
    }
}

/// The TypeScript type of a column's declared type.
fn ts_column_type(model: &SemanticModel, col_type: &ColumnType) -> String {
    match col_type {
        ColumnType::Int | ColumnType::Money | ColumnType::Decimal => "number".to_string(),
        ColumnType::String => "string".to_string(),
        ColumnType::DateTime | ColumnType::Date => "Date".to_string(),
        ColumnType::Bool => "boolean".to_string(),
        ColumnType::Enum(values) => literal_union(values),
        ColumnType::Variation(key) => model
            .variations
            .get(*key)
            .map_or_else(|| "string".to_string(), |v| literal_union(&v.values)),
    }
}

fn literal_union(values: &[String]) -> String {
    if values.is_empty() {
        return "never".to_string();
    }
    values
        .iter()
        .map(|v| ts_string_literal(v))
        .collect::<Vec<_>>()
        .join(" | ")
}

fn ts_string_literal(value: &str) -> String {
    format!("\"{}\"", escape_ts_string(value))
}

fn escape_ts_string(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

fn to_pascal_case(id: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for ch in id.chars() {
        if ch == '_' || ch == '-' {
            upper = true;
            continue;
        }
        if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    if out.is_empty() {
        "Entity".to_string()
    } else {
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use rdra_ish_core::analysis::build_model;
    use rdra_ish_syntax::parse;

    fn model_from(src: &str) -> SemanticModel {
        let (ast, parse_errors) = parse(src);
        assert!(parse_errors.is_empty(), "parse errors: {parse_errors:?}");
        let (model, diags) = build_model(&ast);
        assert!(diags.is_empty(), "unexpected diagnostics: {diags:?}");
        model
    }

    const ORDER_SRC: &str = r#"
entity Order "注文" {
  id:           Int @pk
  status:       Enum(pending, paid, shipped, delivered, cancelled) @default(pending)
  delivered_at: DateTime @null
}
usecase PlaceOrder  "注文確定"
usecase CapturePay  "決済確定"
usecase ShipOrder   "発送"
usecase DeliverOrder "配達確認"
usecase CancelOrder "注文キャンセル"
creates(PlaceOrder, Order)
updates(CapturePay,   Order)
updates(ShipOrder,    Order)
updates(DeliverOrder, Order)
updates(CancelOrder,  Order)
transitions(CapturePay, Order.status, pending -> paid)
transitions(ShipOrder, Order.status, paid -> shipped)
transitions(DeliverOrder, Order.status, shipped -> delivered)
transitions(CancelOrder, Order.status, pending -> cancelled)
sets(usecase::DeliverOrder, Order.delivered_at == present)
"#;

    #[test]
    fn typescript_state_union_snapshot() {
        let model = model_from(ORDER_SRC);
        let collections = collect_entity_state_variants(&model, &[], Caps::STATES);
        insta::assert_snapshot!(emit_typescript_state_unions(&model, &collections));
    }

    /// An Int axis is typed by its column, not by the bounded values the check explored, and
    /// the patterns that differed only there print one object.
    #[test]
    fn int_axis_is_number_and_patterns_merge() {
        let model = model_from(
            r#"
entity Item "商品" {
  id: Int @pk
  status: Enum(active, archived) @default(active)
  stock: Int @default("1")
}
usecase Register "登録"
usecase Restock "入荷"
usecase Archive "廃止"
creates(Register, Item)
updates(Restock, Item)
sets(Restock, Item.stock == 3)
transitions(Archive, Item.status, active -> archived)
forbidden(Item, stock > 4)
"#,
        );
        let collections = collect_entity_state_variants(&model, &[], Caps::STATES);
        let out = emit_typescript_state_unions(&model, &collections);
        assert!(out.contains("stock: number;"), "{out}");
        assert!(
            !out.contains("stock: 1;") && !out.contains("stock: 3;"),
            "{out}"
        );
        assert_eq!(out.matches("status: \"active\";").count(), 1, "{out}");
    }

    #[test]
    fn emitter_matches_helper() {
        let model = model_from(ORDER_SRC);
        let view = View::whole();
        let from_emitter = TypeScriptStateUnionEmitter::default()
            .emit(&model, &view, &Explored::default())
            .unwrap();
        let collections = collect_entity_state_variants(&model, &[], Caps::STATES);
        assert_eq!(
            from_emitter,
            emit_typescript_state_unions(&model, &collections)
        );
    }
}
