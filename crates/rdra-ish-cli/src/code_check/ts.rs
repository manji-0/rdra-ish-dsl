//! The TypeScript backend of `check --code`: the probe and a `tsconfig.rdra.json` that holds
//! only it, `tsc --noEmit -p tsconfig.rdra.json` for `build`, and `node <probe>` for `run`
//! (Node's type stripping runs the probe and the service as they are, so the imports name the
//! `.ts` files). tsc's `file(line,col): error TSxxxx: text` lines are read with their indented
//! continuation lines.

use std::path::{Component, Path, PathBuf};

use rdra_ish_emit::codegen::ir::{ContractDecl, PortMethod};
use rdra_ish_emit::codegen::probe::Probe;
use rdra_ish_emit::codegen::{probe_for, Lang, ProbeBinding};

use super::map::{CompilerMessage, Finding};
use super::{Backend, Target};
use crate::codegen_cmd::stamp;

pub(crate) struct TypeScript;

/// The oldest Node that runs the probe as it is: type stripping without a flag (22.18), and
/// `process.getBuiltinModule` (22.3).
const NODE: &str = "22.18";

/// The file tsc builds: in the root, beside the project's `tsconfig.json`.
const TSCONFIG: &str = "tsconfig.rdra.json";

/// `to` as a path relative to the directory `from`, with `/` separators.
fn relative(from: &Path, to: &Path) -> String {
    let from: Vec<Component> = from.components().collect();
    let to: Vec<Component> = to.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".to_string(); from.len() - common];
    parts.extend(
        to[common..]
            .iter()
            .map(|c| c.as_os_str().to_string_lossy().into_owned()),
    );
    parts.join("/")
}

/// An import specifier of `to` from a file in `from`: `./x.ts`, `../x.ts`.
fn specifier(from: &Path, to: &Path) -> String {
    let rel = relative(from, to);
    if rel.starts_with("../") {
        rel
    } else {
        format!("./{rel}")
    }
}

/// `path` without `.` and `..` components, so two spellings of one file compare equal.
fn normal(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for c in path.components() {
        match c {
            Component::CurDir => {}
            Component::ParentDir if out.file_name().is_some() => {
                out.pop();
            }
            c => out.push(c),
        }
    }
    out
}

/// `[code.ts] service`: `<file relative to rdra.toml>#<exported type>`.
fn service(t: &Target<'_>) -> Option<(PathBuf, String)> {
    let (file, ty) = t.target.service.as_deref()?.rsplit_once('#')?;
    Some((normal(&t.path(Path::new(file))), ty.to_string()))
}

impl TypeScript {
    /// The project's tsconfig `tsconfig.rdra.json` extends: `[code.ts] tsconfig`, else the
    /// root's `tsconfig.json` when it exists.
    fn base_config(t: &Target<'_>) -> Option<PathBuf> {
        match &t.target.tsconfig {
            Some(path) => Some(normal(&t.path(path))),
            None => Some(normal(&t.root().join("tsconfig.json"))).filter(|p| p.is_file()),
        }
    }

    fn tsconfig(&self, t: &Target<'_>, probe: &Path) -> String {
        let root = normal(&t.root());
        let quote = |s: &str| format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""));
        let mut out = String::from(
            "// Generated by rdra-ish codegen (experimental): what `check --code=build` runs tsc on.\n",
        );
        out.push_str("// Never edited by hand: `rdra-ish codegen --code` writes it again.\n{\n");
        let base = Self::base_config(t);
        if let Some(base) = &base {
            out.push_str(&format!(
                "  \"extends\": {},\n",
                quote(&specifier(&root, base))
            ));
        }
        out.push_str("  \"compilerOptions\": {\n");
        if base.is_none() {
            // No project tsconfig: the options the generated code is built with.
            for line in [
                "\"strict\": true,",
                "\"target\": \"es2022\",",
                "\"module\": \"nodenext\",",
                "\"skipLibCheck\": true,",
            ] {
                out.push_str(&format!("    {line}\n"));
            }
        }
        out.push_str("    \"noEmit\": true,\n");
        out.push_str("    \"allowImportingTsExtensions\": true\n");
        out.push_str("  },\n");
        out.push_str(&format!(
            "  \"files\": [{}],\n",
            quote(&relative(&root, &normal(&t.path(probe))))
        ));
        out.push_str("  \"include\": []\n}");
        out
    }
}

impl Backend for TypeScript {
    fn probe(&self, t: &Target<'_>) -> Option<(PathBuf, Probe)> {
        let path = t.target.probe.clone()?;
        let domain = t.generated.domain.as_ref()?;
        let (service_file, ty) = service(t)?;
        let probe_dir = normal(&t.path(&path))
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_default();
        let root = normal(&t.root());
        let traces = t
            .target
            .traces
            .as_ref()
            .map(|traces| relative(&root, &normal(&t.path(traces))));
        let new = t
            .target
            .new
            .clone()
            .unwrap_or_else(|| format!("new service.{ty}()"));
        let binding = ProbeBinding {
            service: format!("{}#{ty}", specifier(&probe_dir, &service_file)),
            module: specifier(&probe_dir, &normal(&t.path(&t.target.domain))),
            conformance: traces.map(|traces| (new, traces)),
        };
        Some((path, probe_for(Lang::TypeScript, domain, &binding)?))
    }

    /// The probe, and `tsconfig.rdra.json` in the root.
    fn extra_files(&self, t: &Target<'_>) -> Vec<(PathBuf, String)> {
        let Some((path, probe)) = self.probe(t) else {
            return Vec::new();
        };
        let hash = &t.generated.model_hash;
        let config = self.tsconfig(t, &path);
        let root = normal(&t.root());
        let dir = normal(t.manifest.dir());
        let config_path = PathBuf::from(relative(&dir, &root)).join(TSCONFIG);
        vec![
            (path, stamp(&probe.text, hash)),
            (config_path, stamp(&config, hash)),
        ]
    }

    fn build_command(&self, t: &Target<'_>) -> Option<Vec<String>> {
        t.target.probe.as_ref()?;
        Some(
            ["tsc", "--noEmit", "--pretty", "false", "-p", TSCONFIG]
                .map(str::to_string)
                .to_vec(),
        )
    }

    fn run_command(&self, t: &Target<'_>) -> Option<Vec<String>> {
        let probe = t.target.probe.as_ref()?;
        t.target.traces.as_ref()?;
        let root = normal(&t.root());
        Some(vec![
            "node".to_string(),
            relative(&root, &normal(&t.path(probe))),
        ])
    }

    fn parse_messages(&self, stdout: &str, stderr: &str) -> Vec<CompilerMessage> {
        let mut out: Vec<CompilerMessage> = Vec::new();
        for line in stdout.lines().chain(stderr.lines()) {
            if let Some(m) = compiler_message(line) {
                out.push(m);
            } else if line.starts_with(' ') {
                if let Some(last) = out.last_mut() {
                    last.text.push('\n');
                    last.text.push_str(line.trim());
                }
            }
        }
        out
    }

    /// The probe line's function returns the service as the contract: TS2741 is one member
    /// missing, TS2739 / TS2740 several, TS2322 a member of another type. tsc has no code for
    /// a contract missing whole; the shared mapping tells it by every member named.
    fn classify(&self, m: &CompilerMessage) -> Finding {
        match m.code.as_deref() {
            Some("TS2739" | "TS2740" | "TS2741" | "TS2420") => Finding::Incomplete,
            Some("TS2322" | "TS2416") => Finding::Signature,
            _ => Finding::Other,
        }
    }

    /// TS2741 names one missing member (`Property 'a' is missing in type ...`); TS2739 lists
    /// them after the type (`... from type 'ShipUseCase': a, b`); TS2740 lists four and counts
    /// the rest (`: a, b, c, d, and 3 more.`).
    fn missing_members(&self, m: &CompilerMessage) -> Option<(Vec<String>, usize)> {
        let first = m.text.lines().next()?;
        match m.code.as_deref()? {
            "TS2741" => {
                let (_, rest) = first.split_once("Property '")?;
                let (name, _) = rest.split_once('\'')?;
                Some((vec![name.to_string()], 0))
            }
            "TS2739" | "TS2740" => {
                let (_, list) = first.rsplit_once("': ")?;
                let mut names = Vec::new();
                let mut more = 0;
                for item in list.trim_end_matches('.').split(", ") {
                    match item
                        .strip_prefix("and ")
                        .and_then(|r| r.strip_suffix(" more"))
                    {
                        Some(n) => more = n.parse().ok()?,
                        None => names.push(item.to_string()),
                    }
                }
                Some((names, more))
            }
            _ => None,
        }
    }

    /// The harness's report: the line after `rdra-ish conformance: `; a Node that runs no
    /// TypeScript as it is, said as such; else the output's last line.
    fn run_failure(&self, stdout: &str, stderr: &str) -> Option<String> {
        let all = format!("{stdout}\n{stderr}");
        if let Some((_, rest)) = all.rsplit_once("rdra-ish conformance: ") {
            return rest.lines().next().map(str::to_string);
        }
        if all.contains("ERR_UNKNOWN_FILE_EXTENSION")
            || all.contains("getBuiltinModule is not a function")
        {
            return Some(format!("node runs no TypeScript as it is: `check --code=run` needs Node {NODE} or later (type stripping), or a `run` command in [code.ts]"));
        }
        all.lines()
            .rev()
            .find(|l| !l.trim().is_empty())
            .map(|l| l.trim().to_string())
    }

    fn method_names(&self, m: &PortMethod) -> Vec<String> {
        vec![format!("prepare{}", m.name), format!("commit{}", m.name)]
    }

    fn entry_names(&self, name: &str) -> Vec<String> {
        vec![format!("run{name}")]
    }

    fn implement_hint(&self, contract: &ContractDecl, service: &str, methods: &[&str]) -> String {
        let ty = service.rsplit_once('#').map_or(service, |(_, ty)| ty);
        format!(
            "give {ty} the members of {} ({})",
            contract.name,
            methods.join(", ")
        )
    }
}

/// One `file(line,col): error TSxxxx: text` line of tsc's plain output.
fn compiler_message(line: &str) -> Option<CompilerMessage> {
    let (head, text) = line.split_once("): error ")?;
    let (file, at) = head.rsplit_once('(')?;
    let (l, c) = at.split_once(',')?;
    let (code, text) = text.split_once(": ")?;
    if !code.starts_with("TS") {
        return None;
    }
    Some(CompilerMessage {
        file: file.to_string(),
        line: l.parse().ok()?,
        column: c.parse().ok()?,
        code: Some(code.to_string()),
        text: text.to_string(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tsc_errors_are_read_with_their_continuation_lines() {
        let out = "src/rdra_contract.ts(9,65): error TS2322: Type 'OrderService' is not assignable to type 'Readonly<{ preparePlace: ... }>'.\n  The types returned by 'preparePlace(...)' are incompatible between these types.\nsrc/order_service.ts(3,1): error TS2304: Cannot find name 'x'.\n";
        let ms = TypeScript.parse_messages(out, "");
        assert_eq!(ms.len(), 2);
        assert_eq!(
            (
                ms[0].file.as_str(),
                ms[0].line,
                ms[0].column,
                ms[0].code.as_deref()
            ),
            ("src/rdra_contract.ts", 9, 65, Some("TS2322"))
        );
        assert!(ms[0].text.contains("'preparePlace(...)'"), "{}", ms[0].text);
        assert_eq!(TypeScript.classify(&ms[0]), Finding::Signature);
        assert_eq!(TypeScript.classify(&ms[1]), Finding::Other);
    }

    #[test]
    fn missing_members_are_read_from_each_code() {
        let message = |code: &str, text: &str| CompilerMessage {
            file: "p.ts".to_string(),
            line: 1,
            column: 1,
            code: Some(code.to_string()),
            text: text.to_string(),
        };
        let some = message(
            "TS2739",
            "Type 'Svc' is missing the following properties from type 'ShipUseCase': prepareShip, commitShip",
        );
        assert_eq!(
            TypeScript.missing_members(&some),
            Some((vec!["prepareShip".to_string(), "commitShip".to_string()], 0))
        );
        let many = message(
            "TS2740",
            "Type 'Svc' is missing the following properties from type 'OrderUseCase': prepareA, commitA, prepareB, commitB, and 2 more.",
        );
        let (names, more) = TypeScript.missing_members(&many).unwrap();
        assert_eq!((names.len(), more), (4, 2));
        let one = message(
            "TS2741",
            "Property 'commitSend' is missing in type 'Svc' but required in type 'SendUseCase'.",
        );
        assert_eq!(
            TypeScript.missing_members(&one),
            Some((vec!["commitSend".to_string()], 0))
        );
        assert_eq!(TypeScript.missing_members(&message("TS2322", "x")), None);
    }

    #[test]
    fn a_node_without_type_stripping_is_named() {
        let old = "node:internal/modules/esm/get_format:218\n  throw new ERR_UNKNOWN_FILE_EXTENSION(ext, filepath);\nTypeError [ERR_UNKNOWN_FILE_EXTENSION]: Unknown file extension \".ts\"\n\nNode.js v20.11.0";
        let said = TypeScript.run_failure("", old).unwrap();
        assert!(said.contains("needs Node 22.18 or later"), "{said}");
        let report = "rdra-ish conformance: traces line 7: after `Pay 1`, the store differs";
        assert_eq!(
            TypeScript.run_failure("", report).as_deref(),
            Some("traces line 7: after `Pay 1`, the store differs")
        );
    }

    #[test]
    fn paths_are_spelled_relative() {
        assert_eq!(
            specifier(Path::new("/p/svc/src"), Path::new("/p/svc/src/d.ts")),
            "./d.ts"
        );
        assert_eq!(
            specifier(Path::new("/p/svc/test"), Path::new("/p/svc/src/d.ts")),
            "../src/d.ts"
        );
        assert_eq!(
            normal(Path::new("/p/model/../svc/./src")),
            PathBuf::from("/p/svc/src")
        );
    }
}
