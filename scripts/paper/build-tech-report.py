#!/usr/bin/env python3
"""Assemble the technical report (#594, T20) as docs/paper/tech-report-full.md.

Usage: python3 -I scripts/paper/build-tech-report.py [--check]

Writes docs/paper/tech-report.md (the report's own text), then each chapter's source document, each
under a chapter heading, with its headings demoted one level and its relative links rewritten to
point from docs/paper/. The theory documents stay the source of truth. The assembled file is
generated, and `--check` fails when it is not what this script writes now. Standard library only.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "docs/paper/tech-report-full.md")

CHAPTERS = [
    ("1 The calculus LC", "docs/paper/calculus.md"),
    ("1 (cont.) Semantics of the full language", "docs/theory/semantics.md"),
    ("2–4 Cones of influence, the sub-lifecycle reduction, instance symmetry", "docs/theory/cones.md"),
    ("5 The native checker", "docs/theory/native.md"),
    ("6 Proofs for any number of rows", "docs/theory/z3.md"),
    ("6 (cont.) The prover as an evaluated heuristic", "docs/paper/eval/prove.md"),
    ("7 Agreement with TLC", "docs/theory/tlc-agreement.md"),
    ("7 (cont.) TLC baseline", "docs/paper/eval/tlc-baseline.md"),
    ("8 Overview, residual risks and known limitations", "docs/theory/README.md"),
    ("8 (cont.) The claims inventory", "docs/theory/claims.md"),
    ("9 The Lean development", "proofs/lean/README.md"),
    ("10 Evaluation", "docs/paper/eval/README.md"),
    ("10.1 Ablation", "docs/paper/eval/ablation.md"),
    ("10.2 Scaling", "docs/paper/eval/scaling.md"),
    ("10.3 Least instance counts", "docs/paper/eval/minimal.md"),
    ("10.4 Determinism", "docs/paper/eval/determinism.md"),
    ("11 Extensions", "docs/paper/extensions.md"),
    ("A Defect record", "docs/paper/evidence/defects.md"),
    ("B Earlier measurements", "docs/paper/evidence/measurements.md"),
    ("C Related work", "docs/paper/related-work.md"),
]

LINK = re.compile(r"\]\((?!https?:|#|mailto:)([^)#\s]+)(#[^)\s]*)?\)")


def rewrite(text, src):
    base = os.path.dirname(os.path.join(ROOT, src))
    here = os.path.join(ROOT, "docs/paper")

    def fix(m):
        target = os.path.normpath(os.path.join(base, m.group(1)))
        return "](" + os.path.relpath(target, here) + (m.group(2) or "") + ")"

    out = []
    fence = False
    for line in text.splitlines():
        if line.startswith("```"):
            fence = not fence
        if not fence and line.startswith("#"):
            line = "#" + line
        out.append(LINK.sub(fix, line) if not fence else line)
    return "\n".join(out)


def build():
    parts = [open(os.path.join(ROOT, "docs/paper/tech-report.md")).read().rstrip(),
             "\n<!-- Generated by scripts/paper/build-tech-report.py. Do not edit: edit the sources. -->\n"]
    for title, src in CHAPTERS:
        body = open(os.path.join(ROOT, src)).read()
        parts.append(f"\n# Chapter {title}\n\n*Source: `{src}`.*\n\n{rewrite(body, src)}\n")
    return "\n".join(parts)


def main(argv):
    text = build()
    if argv[:1] == ["--check"]:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("build-tech-report: docs/paper/tech-report-full.md is stale; run the script")
        print("build-tech-report: up to date")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(f"build-tech-report: wrote {OUT} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main(sys.argv[1:])
